/**
 * РЕЗЕРВНАЯ КОПИЯ БАЗЫ В РЕПОЗИТОРИЙ.
 *
 * Запускается воркфлоу раз в сутки. Читает данные сайта из базы и кладёт
 * в data/live.json — тот самый файл, который до переезда был единственным
 * хранилищем.
 *
 * ПОЧЕМУ ЭТО НЕ «НА ВСЯКИЙ СЛУЧАЙ», А УСЛОВИЕ ПЕРЕЕЗДА.
 *
 * Главная ценность проекта — накопленная история: кто побеждал два года назад,
 * когда взяли чью Столицу. Пока она лежала в git, ей не могло случиться ничего:
 * репозиторий раздаётся тысячами копий, история правок неудаляема, восстановить
 * можно любое состояние на любую дату.
 *
 * В базе всё иначе. Бесплатный проект засыпает без обращений, аккаунт можно
 * потерять, тариф — изменить, а неудачный запрос из SQL-редактора стирает
 * данные молча и навсегда. Без этой выгрузки переезд означал бы обмен вечного
 * хранилища на удобное — то есть ровно то, чего архитектура проекта
 * старательно избегала (см. docs/ARCHITECTURE.md, «Аварийный выход»).
 *
 * С выгрузкой обмен другой: удобство сейчас, а вечность — вчерашней копией.
 * Потерять можно максимум сутки правок.
 *
 * ЗАОДНО ЭТО РАБОЧИЙ ПУТЬ НАЗАД. Файл лежит в том же формате, что читает
 * json-адаптер, поэтому возврат к прежнему устройству — одна строка
 * в config.js: dataSource обратно на 'json'.
 *
 * Запуск: node scripts/backup-from-db.mjs [файл]
 */
import { readFile, writeFile } from 'node:fs/promises';

const outFile = process.argv[2] || 'data/live.json';

/*
  Настройки читаются из config.js, а не из переменных окружения: там уже лежит
  адрес проекта и публичный ключ, и второе место для тех же двух строк
  означало бы, что однажды они разойдутся.

  Публичного ключа достаточно: данные сайта открыты на чтение всем (это
  открытый сайт сообщества). Служебный ключ здесь не нужен и не запрашивается —
  ему нечего делать в воркфлоу.
*/
const { CONFIG } = await import('../config.js');
const CFG = CONFIG.supabase ?? CONFIG.forum?.supabase ?? {};

if (!CFG.url || !CFG.anonKey) {
  console.error(
    'В config.js не заполнен раздел supabase — выгружать нечего.\n' +
      'Порядок подключения описан в docs/FORUM.md.'
  );
  process.exit(1);
}

const base = String(CFG.url)
  .trim()
  .replace(/\/(rest|auth|storage)\/v\d+\/?$/i, '')
  .replace(/\/+$/, '');

const res = await fetch(`${base}/rest/v1/rpc/site_dataset`, {
  method: 'POST',
  headers: {
    apikey: CFG.anonKey,
    ...(String(CFG.anonKey).startsWith('eyJ') ? { Authorization: `Bearer ${CFG.anonKey}` } : {}),
    'Content-Type': 'application/json',
  },
  body: '{}',
});

if (!res.ok) {
  const text = await res.text();
  console.error(`База ответила ошибкой ${res.status}: ${text.slice(0, 400)}`);
  process.exit(1);
}

const data = await res.json();

/*
  ПРОВЕРКА ПЕРЕД ЗАПИСЬЮ — самая важная часть этого скрипта.

  Пустой ответ базы возможен: сбой, недовыполненная схема, случайно стёртые
  таблицы. Записать такой ответ поверх файла значило бы затереть резервную
  копию ровно в тот момент, когда она нужнее всего, — и сделать это молча,
  коммитом от бота, который никто не читает.

  Поэтому пустота считается отказом, а не результатом.
*/
const counts = {
  alliances: data?.alliances?.length ?? 0,
  weeks: data?.weeks?.length ?? 0,
  results: data?.results?.length ?? 0,
  events: data?.events?.length ?? 0,
  texts: data?.texts?.length ?? 0,
};

if (!counts.alliances && !counts.weeks && !counts.results) {
  console.error(
    'База вернула пустой набор данных. Резервную копию НЕ перезаписываю: ' +
      'пустой файл поверх истории — худшее, что может сделать этот скрипт.'
  );
  process.exit(1);
}

/*
  Второй предохранитель: резкая потеря записей.

  Удаление ошибочной недели — обычное дело, а вот исчезновение половины
  альянсов означает, что что-то случилось с базой. Такой случай требует
  человека, а не автоматического коммита.
*/
let previous = null;
try {
  previous = JSON.parse(await readFile(outFile, 'utf8'));
} catch {
  // Файла нет — первая выгрузка, сравнивать не с чем.
}

if (previous?.alliances?.length) {
  const before = previous.alliances.length;
  if (counts.alliances < before * 0.5) {
    console.error(
      `Было ${before} альянсов, стало ${counts.alliances}. Потеря больше половины — ` +
        'это не похоже на обычную правку. Копию не перезаписываю: разберитесь и запустите заново.'
    );
    process.exit(1);
  }
}

/*
  Формат тот же, что писал scripts/pull-sheet.mjs: два пробела отступа
  и перевод строки в конце. Иначе первая же выгрузка покажет в истории
  «изменён весь файл» вместо настоящей разницы.
*/
await writeFile(outFile, `${JSON.stringify(data, null, 2)}\n`, 'utf8');

console.log(
  `Выгружено в ${outFile}: ` +
    `${counts.alliances} альянсов, ${counts.weeks} недель, ${counts.results} результатов, ` +
    `${counts.events} событий, ${counts.texts} текстов.`
);

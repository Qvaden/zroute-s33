/** Те же различимые цвета, что и в демо-данных: цвет альянса работает как цвет команды. */
function hslToHex(h, s, l) {
  s /= 100; l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  const to = (n) => Math.round(255 * f(n)).toString(16).padStart(2, '0');
  return `#${to(0)}${to(8)}${to(4)}`;
}
const COLORS = Array.from({ length: ALLIANCE_COUNT }, (_, i) =>
  hslToHex(Math.round((i * 360) / ALLIANCE_COUNT + (i % 2) * 11) % 360, 62 + (i % 3) * 9, 56 + (i % 4) * 4)
);

/** Ближайший прошедший понедельник от заданной даты, в UTC. */
function mondayOf(date) {
  const d = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  const shift = (d.getUTCDay() + 6) % 7; // 0 = понедельник
  d.setUTCDate(d.getUTCDate() - shift);
  return d;
}

/** Номер недели по ISO — как отправная точка для нумерации. */
function isoWeek(date) {
  const d = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  d.setUTCDate(d.getUTCDate() + 4 - ((d.getUTCDay() + 6) % 7 + 1));
  const yearStart = new Date(Date.UTC(d.getUTCFullYear(), 0, 1));
  return Math.ceil(((d - yearStart) / 86400000 + 1) / 7);
}

const DAY = 86400000;
const firstMonday = mondayOf(new Date());
const firstNumber = isoWeek(firstMonday);

const weeks = Array.from({ length: WEEKS_AHEAD }, (_, i) => {
  const start = new Date(firstMonday.getTime() + i * 7 * DAY);
  const end = new Date(start.getTime() + 6 * DAY);
  const iso = (d) => d.toISOString().slice(0, 10);
  return { id: `W${firstNumber + i}`, number: firstNumber + i, startDate: iso(start), endDate: iso(end) };
});


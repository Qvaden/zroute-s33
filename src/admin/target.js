/**
 * КАКОЙ СЕРВЕР ПАНЕЛЬ ПРАВИТ.
 *
 * Один — тот, что назван в `config.js` строкой `server: 33`. Свой ряд выбора,
 * своя память (`zr33.admin.server`) и список серверов, где право есть, у панели
 * были; их убрали вместе с выбором сервера на сайте по решению владельца. Две
 * цели у одного сайта значат ровно одно: правка однажды уйдёт не туда, а
 * глазами этого не различить — интерфейс тот же, цифры те же, чужая история
 * портится молча.
 *
 * ПОЧЕМУ МОДУЛЬ ОСТАЛСЯ, А НЕ СТРОКА В КАЖДОМ ВЫЗОВЕ.
 *   Число нужно четырём местам: чтению набора, каждой записи в `store.js`,
 *   путям фотографий и ключам черновиков. Разойдись они — панель начала бы
 *   показывать строки одного сервера, а сохранять их в другой.
 *
 * ПРАВА ЗДЕСЬ НЕТ. Право держит база
 *   (`supabase/applied/20261005-site-server-rights.sql`), и панель его
 *   по-прежнему спрашивает. Просто вопрос перестал быть «на какой из серверов»
 *   и стал «пустят ли сюда».
 */
import { siteServer } from '../data/server.js';

/** Роль вошедшего в каждом сервере: карта `forum_my_server_roles()` или null. */
let roles = null;

/** Прочитаны ли права: до ответа панели неоткуда знать, открывать ли экраны. */
let read = false;

function isSiteStaff(account) {
  return Boolean(account) && (account.role === 'admin' || account.role === 'moderator');
}

/**
 * Есть ли у вошедшего право править данные сайта.
 *
 * `roles === null` означает «карты прав нет» — панель ведёт себя как до шага:
 * право ровно у модерации сайта. Пустая карта — это «нигде», и путать её с
 * «не проверяли» нельзя: на пустой карте панель закрыта, на null — открыта
 * владельцу.
 *
 * Забаненный не правит ничьими данными, даже когда карта называет его
 * модератором: карта отвечает по списку участия, а бан смотрит база.
 */
export function canEditSite(account) {
  const server = siteServer();
  if (server === null || !account || account.banned) return false;
  if (roles === null) return isSiteStaff(account);
  return roles[String(server)] === 'moderator';
}

/**
 * Что панель прочитала о правах. Вызывается сразу после входа, до чтения
 * данных: отказ экрана зависит от ответа.
 *
 * @param {{account: any, roles: Record<string, string>|null}} opts
 * @returns {number|null} сервер сайта, если им можно править, иначе null
 */
export function adoptRights({ account, roles: map }) {
  roles = map && typeof map === 'object' && !Array.isArray(map) ? map : null;
  read = true;
  return canEditSite(account) ? siteServer() : null;
}

/**
 * Сервер, который панель правит. Отказ здесь — не вежливость: без номера
 * запись ушла бы в строки без `server_id`, а удаление недели по одному id
 * снесло бы её у всех серверов.
 */
export function panelServer() {
  const server = siteServer();
  if (server === null) {
    throw new Error(
      'В config.js не заполнен server — панель не знает, данные какого сервера ' +
        'она правит. Число стоит в строке «server: 33».'
    );
  }
  return server;
}

/**
 * Сервер для папок черновиков — тот же, что у чтений и записей.
 *
 * В отличие от `panelServer()` отказа здесь нет: черновик читают и тогда, когда
 * права ещё не прочитаны (каркас панели в превью, старая вкладка после пуша), а
 * пустая папка для человека лучше сорванной отрисовки экрана.
 */
export function draftServer() {
  return siteServer();
}

/** Права прочитаны и сервер сайта назван: кнопки записи имеют смысл. */
export function rightsRead() {
  return read && siteServer() !== null;
}

/** Выход из панели: чужие права не должны пережить чужой вход. */
export function forgetRights() {
  roles = null;
  read = false;
}

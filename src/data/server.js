import { CONFIG } from '../../config.js';

/**
 * Номер сервера из config.js или null, если там не число.
 *
 * Пустота проверена отдельно: Number('') и Number(null) дают ноль, который
 * проходит как целое число. Сервера с номером 0 в базе нет (колонка проверяет
 * 1..999), поэтому пустое поле в config.js означало бы запрос за пустым
 * набором вместо понятного отказа.
 */
export function siteServer() {
  const raw = CONFIG.server;
  if (raw === null || raw === undefined || String(raw).trim() === '') return null;

  const n = Number(raw);
  return Number.isInteger(n) ? n : null;
}

/**
 * Тело вызова `site_dataset`. Без номера база сама подставляет сервер по
 * умолчанию — тот же порядок, что у колонок в миграции, поэтому пустое поле в
 * config.js не ломает чтение: экран просто покажет ровно тот набор, о котором
 * договорилась база.
 */
export function datasetBody(server = siteServer()) {
  return server === null ? {} : { p_server: server };
}

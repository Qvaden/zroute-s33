/**
 * СЕРВЕР, ЧЬИ ДАННЫЕ САЙТА ПОКАЗЫВАЕТ СТРАНИЦА И ПРАВИТ ПАНЕЛЬ.
 *
 * Мультиаренда началась с форума: там сервер выбирается адресом (`?server=N`),
 * живёт в состоянии ленты и спрашивается у базы. С этого шага выбор стал общий:
 * адрес и память браузера читает `src/logic/server-choice.js`, а здесь лежит
 * то, чем этот выбор заканчивается для данных сайта.
 *
 * ДВА ЧИСЛА В ОДНОМ ФАЙЛЕ — И ОНИ ЗНАЧИТ РАЗНОЕ.
 *   `siteServer()` — сервер самого сайта, из `config.js`. Его правит панель и
 *   к нему относится снимок `data/live.json`.
 *   `viewServer()` — сервер, который человек выбрал глазами: адрес, память
 *   браузера, а если ничего не выбрано — сервер сайта. Он только читает.
 *
 * ПОЧЕМУ ПАНЕЛЬ НЕ СЛЕДУЕТ ЗА ПЕРЕКЛЮЧАТЕЛЕМ.
 *   Переключатель стоит в шапке и виден на вкладке «Панель». Умел бы он менять
 *   цель записи — один случайный щелчок отправил бы правку в чужой набор, а
 *   человек этого бы не заметил: интерфейс тот же. Поэтому значение по умолчанию
 *   и у чтения, и у записи — сервер сайта, а выбор зрителя передаёт явно тот,
 *   кто показывает страницу. Панель же читает и правит одно и то же число:
 *   разолись бы эти два в разные серверы, и она показывала бы строки 44-го, а
 *   сохраняла их в 33-й.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А СТРОКА В КАЖДОМ АДАПТЕРЕ.
 *   Число нужно трём местам: чтению сайта (`src/data/adapters/supabase.js`),
 *   чтению панели и записи (`src/admin/store.js`). Разойдись они — панель
 *   начнёт править один сервер, а показывать другой, и это тот редкий случай,
 *   где ошибка не бросается в глаза: всё выглядит целым.
 *
 * ПОЧЕМУ ЗАПИСЬ ТРЕБУЕТ ЧИСЛО, А ЧТЕНИЕ — НЕТ.
 *   Прочитать «чей набор» можно и без номера: база отдаёт значение по умолчанию,
 *   и на экране будет ровно тот сервер, о котором договорились. Запись без
 *   номера означает другое: удаление недели по одному её id снесло бы «W1»
 *   на всех серверах, а вставка строки без `server_id` попала бы в ключ, которого
 *   панель не видит. Поэтому пишущая сторона требует число, а не додумывает его.
 */
import { CONFIG } from '../../config.js';
import { serverFromHash, readServerChoice, resolveServer } from '../logic/server-choice.js';

/** Номер сервера из config.js или null, если там не число. */
export function siteServer() {
  /*
    Пустота проверена отдельно: Number('') и Number(null) дают ноль, который
    проходит как целое число. Сервера с номером 0 в базе нет (колонка проверяет
    1..999), поэтому пустое поле в config.js означало бы запрос за пустым
    набором вместо понятного отказа.
  */
  const raw = CONFIG.server;
  if (raw === null || raw === undefined || String(raw).trim() === '') return null;

  const n = Number(raw);
  return Number.isInteger(n) ? n : null;
}

/**
 * Сервер, который человек выбрал глазами: адрес, затем память браузера, затем
 * сервер сайта. От сервера сайта отличается ровно тем, что его нельзя ни во
 * что записать: он меняется щелчком в шапке и живёт, пока его не перещёлкнули.
 *
 * Память браузера читает общий модуль выбора, а не своё поле: раз выбор один на
 * весь сайт, лента форума и рейтинг обязаны называть одно число, иначе плашка
 * хроники на странице форума читала бы данные одного сервера под лентой другого.
 */
export function viewServer() {
  const address = typeof location === 'undefined' ? null : serverFromHash(location.hash);
  /*
    Порядок «адрес > память» записан один раз — в resolveServer. Здесь он
    заканчивается сервером сайта: у данных набора без номера не бывает, база
    подставляет своё значение по умолчанию, и пустой выбор означает «показывай
    свой», а не «не фильтруй ничего», как на форуме.
  */
  return resolveServer({ address, stored: readServerChoice() }) ?? siteServer();
}

/**
 * Тело вызова `site_dataset`. Без номера база сама подставляет сервер по
 * умолчанию — тот же порядок, что у колонок в миграции.
 *
 * Значение по умолчанию — сервер сайта, а не выбор зрителя: его передаёт явно
 * тот, кто показывает страницу, а панель, вызывая функцию без аргумента, остаётся
 * при своём наборе.
 */
export function datasetBody(server = siteServer()) {
  return server === null ? {} : { p_server: server };
}

/**
 * Номер сервера для записи. Отказ здесь — не вежливость: без него панель
 * отправляла бы строки без `server_id` и удаляла бы чужие недели одним id.
 */
export function writeServer() {
  const server = siteServer();
  if (server === null) {
    throw new Error(
      'В config.js не заполнен server — панель не знает, данные какого сервера ' +
        'она правит. Число стоит в строке «server: 33».'
    );
  }
  return server;
}

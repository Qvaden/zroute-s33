/**
 * МЕТКА УСТРОЙСТВА ЗАБАНЕННОГО.
 *
 * ЗАЧЕМ ОНА. Запрет писать действует на аккаунт: нарушитель заводит второй ник
 * и продолжает. Бан по IP в этом проекте невозможен — сайт статический, запросы
 * идут из браузера посетителя напрямую в базу, и адрес человека не видит ни
 * один наш код (база не отдаёт IP ни в строку таблицы, ни в правило доступа).
 * Поэтому используется то, что действительно видно: браузер нарушителя сам
 * запоминает запрет и не даёт завести новый аккаунт на этом устройстве.
 *
 * ГРАНИЦЫ, КОТОРЫЕ НЕЛЬЗЯ ЗАМАЛЧИВАТЬ. Это препятствие, а не защита: метка
 * лежит в localStorage и снимается очисткой данных сайта, другим браузером или
 * другим телефоном. Называть её «баном по железу» значило бы пообещать
 * владельцу то, чего нет, поэтому и в коде, и в панели она называется меткой.
 *
 * СРОК. Метка ставится один раз и живёт DEVICE_BAN_DAYS, а не продлевается
 * каждым заходом: устройство может быть общим (семья, школа, кафе), и вечная
 * блокировка наказывала бы не нарушителя, а того, кто сел за компьютер следом.
 *
 * КОГДА СПАДАЕТ. Как только этот же аккаунт заходит без запрета — значит, меру
 * сняли, и держать метку незачем. Чужой незабаненный аккаунт на том же
 * устройстве метку не снимает: иначе второй ник обходил бы её одним входом.
 */

const KEY = 'zr33.deviceban';

/** Сколько дней устройство помнит запрет. */
export const DEVICE_BAN_DAYS = 14;

const MS = DEVICE_BAN_DAYS * 24 * 60 * 60 * 1000;

/*
  localStorage умеет бросать: приватный режим, отключённые куки, открытие
  страницы из файла. Метка — не то, ради чего стоит ронять вход, поэтому все
  три обращения обёрнуты: нет хранилища — нет и метки.
*/
const readRaw = () => { try { return localStorage.getItem(KEY); } catch { return null; } };
const writeRaw = (value) => { try { localStorage.setItem(KEY, value); } catch { /* некуда писать */ } };
const dropRaw = () => { try { localStorage.removeItem(KEY); } catch { /* нечего стирать */ } };

/**
 * Разбор записи. Метка с истёкшим сроком или мусор вместо неё считаются
 * отсутствием метки, а хранилище сразу чистится: иначе просроченная запись
 * лежала бы вечно и попадала в каждый следующий разбор.
 *
 * @returns {{userId: string, nick: string, until: Date}|null}
 */
function parse(raw) {
  if (!raw) return null;
  let mark = null;
  try { mark = JSON.parse(raw); } catch { mark = null; }
  const until = Date.parse(mark?.until ?? '');
  if (!mark?.userId || !Number.isFinite(until)) { dropRaw(); return null; }
  if (until <= Date.now()) { dropRaw(); return null; }
  return { userId: String(mark.userId), nick: String(mark.nick ?? ''), until: new Date(until) };
}

/** Действующая метка устройства: null, если её нет или срок вышел. */
export function deviceBan() {
  return parse(readRaw());
}

/**
 * Привести метку в соответствие с тем, что база сказала про вошедшего.
 *
 * Зовётся из currentUser() обоих адаптеров — единственного места, где сайт
 * узнаёт, кто вошёл и действует ли запрет. Отдельной кнопки «пометить
 * устройство» в панели нет намеренно: модератор и так применяет запрет, а
 * вторая кнопка означала бы две меры, которые можно применить невпопад.
 *
 * @param {{id?: string, nick?: string, banned?: boolean}|null} me
 */
export function syncDeviceBan(me) {
  const id = String(me?.id ?? '');
  if (!id) return;
  const mark = deviceBan();

  if (me.banned) {
    // Действующая метка не перезаписывается: срок идёт от первого запрета на
    // этом устройстве, иначе следующий нарушитель обнулил бы часы.
    if (mark) return;
    writeRaw(JSON.stringify({
      userId: id,
      nick: String(me.nick ?? ''),
      at: new Date().toISOString(),
      until: new Date(Date.now() + MS).toISOString(),
    }));
    return;
  }

  if (mark && mark.userId === id) dropRaw();
}

/**
 * Отказ при регистрации — текст, который человек увидит в форме.
 *
 * Говорит три вещи: что закрыто, до когда и что делать, если устройство общее.
 * Обещать, что метку снимут по просьбе, нельзя — её не видно ни в какой
 * панели, — поэтому речь идёт о снятии самого запрета.
 */
export function deviceBanRefusal(mark) {
  const who = mark?.nick ? `аккаунт «${mark.nick}»` : 'один из аккаунтов';
  const until = mark?.until ? mark.until.toLocaleDateString('ru-RU') : '';
  return (
    `Регистрация с этого устройства закрыта: ${who} под запретом модерации.`
    + (until ? ` Устройство освободится ${until}.` : '')
    + ' Если запрет снимут раньше, метка спадёт при следующем входе под этим ником.'
    + ' Если компьютер общий и нарушали не вы — напишите модератору.'
  );
}

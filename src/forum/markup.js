/**
 * Текст записи в разметку.
 *
 * ПОРЯДОК ДЕЙСТВИЙ ЗДЕСЬ — И ЕСТЬ ЗАЩИТА.
 *
 * Сначала esc() на всём абзаце, потом расстановка тегов. Наоборот делать
 * нельзя ни при каких обстоятельствах: экранирование съело бы собственные
 * теги, а если экранировать «аккуратно, кроме своих» — появляется ровно то
 * место, где ошибаются все.
 *
 * @param {string} src
 * @param {{mentions?: Set<string>|string[]}} [opts] Ники, которые есть на форуме:
 *   упоминание превращается в ссылку только для них.
 */
export function renderMarkup(src, opts = {}) {
  const text = String(src ?? '').replace(/\r\n/g, '\n').trim();
  if (!text) return '';

  const known = opts.mentions instanceof Set
    ? opts.mentions
    : new Set((opts.mentions ?? []).map((n) => String(n).toLowerCase()));

  const blocks = [];
  /*
    Три буфера вместо одного: строки одного вида идут подряд и склеиваются,
    а строка другого вида закрывает предыдущий блок.

    Первая версия склеивала абзацы, проверяя последний собранный блок строкой
    вроде `prev.endsWith('</p>__closed')` — условие, которое не выполняется
    никогда, поэтому пустая строка не разделяла абзацы: два абзаца слипались
    в один через перенос. Явный буфер такого не допускает: пустая строка
    просто закрывает его.
  */
  let para = null;
  let list = null;
  let quote = null;

  const closePara = () => {
    if (para) { blocks.push(`<p class="fm-p">${para.join('<br>')}</p>`); para = null; }
  };
  const closeList = () => {
    if (list) { blocks.push(`<ul class="fm-list">${list.join('')}</ul>`); list = null; }
  };
  const closeQuote = () => {
    if (quote) { blocks.push(`<blockquote class="fm-quote">${quote.join('<br>')}</blockquote>`); quote = null; }
  };
  const closeAll = () => { closePara(); closeList(); closeQuote(); };

  for (const rawLine of text.split('\n')) {
    const line = rawLine.trimEnd();

    // Пустая строка — разделитель: закрывает всё, что собиралось.
    if (!line.trim()) { closeAll(); continue; }

    const asList = line.match(/^\s*[-•]\s+(.+)$/);
    if (asList) {
      closePara();
      closeQuote();
      (list ??= []).push(`<li>${inline(asList[1], known)}</li>`);
      continue;
    }

    const asQuote = line.match(/^\s*>\s?(.*)$/);
    if (asQuote) {
      closePara();
      closeList();
      (quote ??= []).push(inline(asQuote[1], known));
      continue;
    }

    closeList();
    closeQuote();
    (para ??= []).push(inline(line, known));
  }

  closeAll();
  return blocks.join('');
}

/**
 * Разметка внутри строки.
 *
 * Каждое правило работает по уже экранированному тексту и вставляет только
 * свои теги. Содержимое подставляется как есть — оно безопасно, потому что
 * прошло esc() строкой выше.
 */
function inline(raw, known) {
  let s = esc(raw);

  /*
    Порядок правил важен для парных знаков: «**» надо разобрать раньше «*»,
    иначе жирный текст распадётся на два курсива с пустотой между ними.
  */
  s = s.replace(/\*\*(?=\S)([\s\S]*?\S)\*\*/g, '<strong>$1</strong>');
  s = s.replace(/__(?=\S)([\s\S]*?\S)__/g, '<u>$1</u>');
  s = s.replace(/~~(?=\S)([\s\S]*?\S)~~/g, '<s>$1</s>');
  s = s.replace(/(^|[^*\w])\*(?=\S)([^*\n]*?\S)\*(?!\w)/g, '$1<em>$2</em>');

  /*
    Цвет: [c=gold]текст[/c].

    Имя цвета проверяется по словарю, и в разметку уходит КЛАСС, а не строка
    автора. Неизвестное имя оставляет текст как есть вместе с квадратными
    скобками — так человек видит, что опечатался, вместо молчаливой потери
    оформления.
  */
  s = s.replace(/\[c=([a-z]{1,10})\]([\s\S]*?)\[\/c\]/gi, (m, name, inner) => {
    const key = String(name).toLowerCase();
    return COLORS[key] ? `<span class="fm-c fm-c--${key}">${inner}</span>` : m;
  });

  s = linkify(s);
  s = mentionify(s, known);
  return s;
}

/**
 * Ссылки.
 *
 * Схему проверяем через safeUrl: `javascript:` внутри href остаётся рабочим
 * кодом даже после честного экранирования кавычек.
 *
 * Показываем домен, а не полный адрес: на телефоне длинная ссылка ломает
 * вёрстку, а ссылка-простыня — стандартный вид рекламы, которую правила
 * и так запрещают.
 */
function linkify(escaped) {
  return escaped.replace(/https?:\/\/[^\s<]+/g, (match) => {
    const trimmed = match.replace(/[.,;:!?)»"']+$/, '');
    const tail = match.slice(trimmed.length);

    const raw = trimmed.replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"');
    const url = safeUrl(raw);
    if (!url) return match;

    let label = trimmed;
    try {
      label = new URL(raw).hostname.replace(/^www\./, '');
    } catch {
      // Адрес не разобрался — покажем как есть, он уже экранирован.
    }

    return `<a href="${esc(url)}" target="_blank" rel="noopener noreferrer ugc">${esc(label)}</a>${tail}`;
  });
}

/**
 * УПОМИНАНИЯ: @ник.
 *
 * Ссылкой становится только СУЩЕСТВУЮЩИЙ ник — те, что переданы в known.
 * Иначе «@всем» и «почта@домен» превращались бы в ссылки на несуществующие
 * страницы, а человек решал бы, что сайт врёт.
 *
 * Ники бывают из двух слов, но в упоминании пробел не поддерживается
 * намеренно: иначе «@Тёмный решил» не отличить от «@Тёмный Лорд». Кто хочет
 * быть упомянутым — пишет ник без пробела, и это видно в его профиле.
 */
function mentionify(escaped, known) {
  if (!known?.size) return escaped;

  return escaped.replace(/(^|[\s(«"'>])@([\p{L}\p{N}_-]{2,24})/gu, (match, before, nick) => {
    if (!known.has(nick.toLowerCase())) return match;
    return `${before}<a class="fm-mention" href="#/user/${encodeURIComponent(nick)}">@${esc(nick)}</a>`;
  });
}

/**
 * НИКИ, УПОМЯНУТЫЕ В ТЕКСТЕ.
 *
 * Нужны при публикации: по ним рассылаются уведомления. Возвращает ники
 * в том виде, в каком их написали, — сверять с базой будет вызывающий,
 * потому что здесь нет доступа к списку участников.
 *
 * @param {string} src
 * @returns {string[]}
 */
export function extractMentions(src) {
  const out = new Set();
  for (const m of String(src ?? '').matchAll(/(^|[\s(«"'>])@([\p{L}\p{N}_-]{2,24})/gu)) {
    out.add(m[2]);
  }
  return [...out];
}

/**
 * Текст без разметки — для выжимки в ленте и для уведомлений.
 *
 * Убираем знаки разметки, а не прячем их стилями: в выжимке «**Разбор** VS»
 * должно читаться как «Разбор VS», иначе звёздочки выглядят опечаткой.
 */
export function stripMarkup(src) {
  return String(src ?? '')
    .replace(/\[c=[a-z]{1,10}\]([\s\S]*?)\[\/c\]/gi, '$1')
    .replace(/\*\*([\s\S]*?)\*\*/g, '$1')
    .replace(/__([\s\S]*?)__/g, '$1')
    .replace(/~~([\s\S]*?)~~/g, '$1')
    .replace(/\*([^*\n]*?)\*/g, '$1')
    .replace(/^\s*[->•]\s+/gm, '')
    .replace(/\s+/g, ' ')
    .trim();
}

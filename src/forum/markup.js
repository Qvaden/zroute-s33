/**
 * ЧТО УМЕЕТ РАЗМЕТКА.
 *
 * Список нарочно короткий. Каждая конструкция — это то, что человек должен
 * запомнить, и то, что может сработать не там, где он ждал. Заголовков нет:
 * пост это не документ, а сообщение, и заголовок у него уже есть отдельным
 * полем.
 */

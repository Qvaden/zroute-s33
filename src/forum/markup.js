  gold: { label: 'золотой', tone: '#ffc93c' },
  green: { label: 'зелёный', tone: '#4fd98a' },
  cyan: { label: 'бирюзовый', tone: '#5ce0dd' },
  blue: { label: 'синий', tone: '#6fa8ff' },

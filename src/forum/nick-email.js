/**
 * НИК → АДРЕС ПОЧТЫ.
 *
 * Вход у нас по нику, почты нет. Но система входа Supabase без адреса почты
 * не работает, поэтому ник превращается в адрес на вымышленном домене,
 * куда никто ничего не отправляет.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ТРИ СТРОКИ В АДАПТЕРЕ.
 *
 * Первая версия делала ровно три строки: пробелы в точки, всё в нижний
 * регистр, приписать домен. На живой системе входа это развалилось сразу:
 *
 *   linktest77   → принято
 *   Ковыль       → «Unable to validate email address: invalid format»
 *   Тёмный Лорд  → то же
 *   Игрок77      → то же
 *
 * Supabase не принимает в адресе ничего, кроме ASCII. А аудитория здесь
 * играет под русскими никами — то есть регистрация не работала для почти
 * всех, и сообщение об ошибке причину не называло.
 *
 * Значит превращение ника в адрес — не мелкая деталь адаптера, а отдельная
 * задача со своими правилами, которую нужно проверять тестами. Отсюда файл.
 *
 * ГЛАВНОЕ ТРЕБОВАНИЕ: РАЗНЫЕ НИКИ — РАЗНЫЕ АДРЕСА.
 *
 * Если два разных ника дадут один адрес, второй человек при регистрации
 * получит «занято», а при входе попадёт в чужой аккаунт. Это худший исход
 * из возможных, и одной транслитерацией его не избежать: «Лёша» и «Леша»
 * в латинице совпадут, «Игрок!» и «Игрок?» после чистки — тоже.
 *
 * Поэтому к переведённой части всегда добавляется короткий отпечаток,
 * посчитанный от ТОЧНОГО ника. Совпадение отпечатков у разных ников
 * возможно, но требует специального подбора, а не случайного совпадения
 * похожих ников — а подбор здесь ничего не даёт: пароль всё равно чужой.
 *
 * Сам ник при этом хранится в базе как есть, русскими буквами. Адрес —
 * служебная строка, которую человек никогда не увидит.
 */

/**
 * Таблица перевода. Составлена под чтение вслух, а не под стандарт:
 * «щ» как «sch», а не «shch», «ё» отдельно от «е» — иначе «Лёша» и «Леша»
 * дают одинаковую основу, и различать их будет только отпечаток.
 */
const TRANSLIT = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh',
  з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c',
  ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu',
  я: 'ya',
  // Украинские и белорусские буквы: сообщество разноязычное, и ник
  // с «і» или «ў» не должен упираться в отказ на пустом месте.
  і: 'i', ї: 'yi', є: 'ye', ґ: 'g', ў: 'w',
};

/**
 * Отпечаток ника: 8 шестнадцатеричных знаков.
 *
 * Считается по FNV-1a — простой и давно известный способ, которого здесь
 * достаточно: это не защита, а различитель. Стойкая к подбору функция
 * потребовала бы асинхронности (WebCrypto) в месте, где нужна обычная
 * строка, и ничего бы не добавила: адрес и так виден только базе.
 */
function fingerprint(text) {
  let hash = 0x811c9dc5;
  for (const char of String(text)) {
    hash ^= char.codePointAt(0);
    // Умножение на 16777619 в 32 битах, без потери точности на больших числах.
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, '0');
}

/**
 * Ник в локальную часть адреса.
 *
 * @param {string} nick
 * @returns {string} Только ASCII: буквы, цифры, точка и дефис.
 */
export function nickToLocalPart(nick) {
  /*
    Пробелы по краям и двойные пробелы внутри убираем ДО отпечатка, теми же
    правилами, что и validateNick в rules.js. Иначе «Ковыль» и «Ковыль »
    дадут разные отпечатки: ник в базе один и тот же (валидатор его подрезал),
    а адрес — другой, и человек не сможет войти.
  */
  const source = String(nick ?? '').trim().replace(/\s+/g, ' ');
  const mark = fingerprint(source.toLowerCase());

  const base = source
    .toLowerCase()
    // Перевод по таблице; всё, чего в ней нет, разбирается ниже.
    .replace(/[а-яёіїєґў]/g, (c) => TRANSLIT[c] ?? '')
    // Пробел внутри ника — обычное дело, в адресе его быть не может.
    .replace(/\s+/g, '-')
    // Остальное: цифры и латиница остаются, прочее выбрасывается.
    .replace(/[^a-z0-9.-]/g, '')
    // Точка и дефис по краям делают адрес недействительным.
    .replace(/^[.-]+|[.-]+$/g, '')
    // Две точки подряд запрещены правилами адресов почты.
    .replace(/\.{2,}/g, '.')
    .slice(0, 24);

  /*
    Ник может состоять целиком из символов, которых в адресе быть не может —
    например «★★★». Тогда основы не остаётся, и адрес держится на одном
    отпечатке. Это рабочий случай, а не ошибка: такой ник в игре допустим.
  */
  return base ? `${base}-${mark}` : `u-${mark}`;
}

/**
 * Полный адрес для системы входа.
 *
 * @param {string} nick
 * @param {string} domain
 */
export function nickToEmail(nick, domain) {
  return `${nickToLocalPart(nick)}@${domain}`;
}

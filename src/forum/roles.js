/**
 * РОЛИ — ОДИН СЛОВАРЬ НА САЙТ И НА ПАНЕЛЬ.
 *
 * Их ТРИ, и это осознанное сокращение.
 *
 * Сначала было пять: владелец, администратор, модератор, редактор, участник.
 * Разделение казалось правильным — «вносящий итоги VS не обязан разбирать
 * споры», — но оно из другого масштаба. На форуме с десятком помощников такое
 * деление экономит доверие; на сайте одного игрового сервера, где помощников
 * один-два, оно только добавляет сущностей, которые надо помнить, объяснять
 * и выдавать по отдельности.
 *
 * Осталось то, что различается по существу:
 *
 *   владелец  — тот, чей это сайт. Ровно один, и это правило держит база.
 *   модератор — тот, кому доверили: и форум, и данные сайта.
 *   участник  — все остальные.
 *
 * ЧТО ЗДЕСЬ ЕСТЬ. Только внешний вид: как называть, каким цветом, каким
 * значком. Права живут в db/account.js и, по-настоящему, в правилах доступа
 * базы. Разделение важное: цвет подписи можно менять свободно, права нельзя.
 */

/**
 * @typedef {Object} RoleLook
 * @property {string} label  Как называть.
 * @property {string} short  Короткая подпись — для мест, где мало места.
 * @property {string} glyph  Значок. Один символ: два уже мусор.
 * @property {string} tone   Цвет метки.
 */

/** @type {Record<string, RoleLook>} */
export const ROLE_LOOK = {
  /*
    Владелец. Корона — единственный значок, который в игровой среде читается
    однозначно и не требует подписи.

    В базе это роль admin, и на неё стоит ограничение: такая запись может быть
    только одна. То есть «владелец один» — не договорённость, а правило,
    которое нельзя обойти даже запросом мимо сайта.
  */
  owner: {
    label: 'владелец',
    short: 'владелец',
    glyph: '👑',
    tone: '#ffc93c',
  },
  /*
    Модератор. Может всё, кроме назначения роли и сброса пароля — то есть
    кроме власти над самими правами. Это единственная граница, которая
    осталась после сокращения, и она на месте: иначе модератор назначил бы
    себя владельцем, и разница между ролями исчезла бы.
  */
  moderator: {
    label: 'модератор',
    short: 'модератор',
    glyph: '🛡',
    tone: '#ff6a2b',
  },
  member: {
    label: 'участник',
    short: '',
    glyph: '',
    tone: '',
  },
};

/**
 * Какую подпись показать.
 *
 * @param {{role?: string}|null} account
 * @returns {'owner'|'moderator'|'member'}
 */
export function roleKey(account) {
  if (!account) return 'member';
  // В базе владелец — это роль admin, единственная такая запись.
  if (account.role === 'admin') return 'owner';
  if (account.role === 'moderator') return 'moderator';
  return 'member';
}

/** @param {any} account */
export function roleLook(account) {
  return ROLE_LOOK[roleKey(account)] ?? ROLE_LOOK.member;
}

/**
 * Подпись словом. Для мест, где значок не нужен.
 * @param {any} account
 */
export function roleLabel(account) {
  return roleLook(account).label;
}

/**
 * Метка рядом с ником: значок и слово.
 *
 * Участник метки не получает вовсе, и это осознанно. Если подписать всех,
 * подпись перестаёт значить что-либо: она нужна, чтобы отличить того, кто
 * отвечает за сайт, от остальных. «Участник» рядом с каждым ником — шум
 * в каждой строке ленты.
 *
 * ВАЖНО: возвращает разметку, поэтому сюда не подставляется ничего, кроме
 * заранее известных строк из словаря выше.
 *
 * @param {any} account
 * @param {{short?: boolean}} [opts]
 */
export function roleBadge(account, { short = false } = {}) {
  const key = roleKey(account);
  if (key === 'member') return '';

  const look = ROLE_LOOK[key];
  const text = short ? look.short : look.label;
  if (!text) return '';

  return (
    `<span class="role-badge role-badge--${key}" style="--role-tone:${look.tone}"` +
    (text ? ` title="${text}" role="img" aria-label="${text}"` : '') +
    '>' +
    (look.glyph ? `<i aria-hidden="true">${look.glyph}</i>` : '') +
    `<b>${text}</b>` +
    '</span>'
  );
}

/**
 * СРОКИ ОТВЕТА МОДЕРАЦИИ (SLA) — одна линейка возраста заявки.
 *
 * Пункт пришёл с форума сообщества, где очередь обращений размечают уровнем
 * просрочки: «новое», «скоро срок», «просрочено», — и дежурный сверху читает
 * то, что ждёт ответа дольше всего. Донор считает уровень на чтении по возрасту
 * заявки, и мы считаем так же: ни колонок в базе, ни будильника не заведено
 * намеренно. Уровень — наблюдение, а не право: на него нельзя сослаться в
 * отказе или санкции, поэтому он и не переживает перезагрузку страницы, а
 * пересчитывается каждый раз из `createdAt`, который пришёл из базы.
 *
 * Числа не перенесены дословно. Донор держит «скоро срок» на четырёх часах,
 * потому что у него очередь делят несколько модераторов со сменами. У нас
 * форум читает один дежурный не по расписанию, и четырёхчасовая линейка
 * покраснила бы «просрочено» каждый обычный вечер: метка, которая включается
 * всегда, перестаёт что-то значить. Поэтому сутки на «скоро» и трое на
 * «просрочено» — тот же срок, который публично обещан игроку под правилами.
 *
 * Пустое и бессмысленное время — уровень «свежая», метки нет: очередь не
 * должна врать о сроке там, где не знает даже даты.
 */
import { CONFIG } from '../../config.js';

const L = CONFIG.forum.limits;

/** Метка уровня. Слово одно на весь сайт; его сторожит тест. */
export const SLA_LABELS = {
  soon: 'скоро срок',
  late: 'просрочено',
};

/**
 * Возраст заявки на язык дежурного: `fresh` — раньше срока, `soon` — сутки
 * ждут, `late` — обещание игроку уже не выдержать.
 *
 * @param {Date|number|string|null} createdAt
 * @param {Date} [now]
 * @returns {'fresh'|'soon'|'late'}
 */
export function slaLevel(createdAt, now = new Date()) {
  const at = createdAt instanceof Date ? createdAt : new Date(createdAt ?? NaN);
  const then = at.getTime();
  const atNow = now.getTime();
  if (!Number.isFinite(then) || !Number.isFinite(atNow)) return 'fresh';
  const ageHours = (atNow - then) / 3600000;
  if (ageHours >= L.slaOverdueHours) return 'late';
  if (ageHours >= L.slaDueSoonHours) return 'soon';
  return 'fresh';
}

/**
 * Публичное обещание: сколько игрок ждёт ответа. Число берётся из той же
 * границы, которая красит метку «просрочено», — иначе страница обещала бы
 * одно, а очередь дежурного считала бы по другому.
 */
export function slaPromiseDays() {
  return Math.round(L.slaOverdueHours / 24);
}

export function slaPromiseLine() {
  return `Обычно отвечаем в течение ${slaPromiseDays()} суток.`;
}

const clip = (s, max) => (s.length > max ? `${s.slice(0, max).replace(/\s+\S*$/, '')}…` : s);

export const cleanTitle = (value) => String(value ?? '')
  .replace(/[\p{Extended_Pictographic}\uFE0F\u200D]/gu, '')
  .replace(/\s+/g, ' ')
  .replace(/^[\s:.,;—–-]+|[\s:.,;—–-]+$/g, '')
  .trim();


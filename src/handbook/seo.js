export function seoFor(node) {
  const named = GUIDE_SEO[node.id];
  if (named) {
    return {
      title: clip(named.title, 90),
      heading: named.heading,
      description: clip(named.description, 158),
    };
  }

  const title = cleanTitle(node.title);
  if (node.children.length) {
    return {
      title: clip(`${title} — гайды и разборы ${GAME}`, 90),
      heading: `${title}: гайды и разборы`,
      description: clip(`Раздел «${title}» справочника ${GAME}: список гайдов, механики и советы.`, 158),
    };
  }

  return {
    title: clip(`${title} — гайд по ${GAME}`, 90),
    heading: `${title} — гайд по ${GAME}`,
    description: clip(`${title}: официальный гайд по игре ${GAME}.`, 158),
  };
}



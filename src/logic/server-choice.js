/**
 * ВЫБОР СЕРВЕРА: ОДНА ПАМЯТЬ НА ВЕСЬ САЙТ.
 *
 * Мультиаренда началась с форума: лента читает `?server=N`, помнит выбор
 * браузера и смотрит список серверов в базе. Данные сайта (рейтинг, кварт,
 * хронология, тексты) долго этого выбора не знали — показывали сервер из
 * `config.js`. Развести их по разным числам нельзя на одном экране: форум
 * берёт ленту у своего выбора, а плашка хроники на той же странице — у данных
 * сайта. Два разных переключателя показали бы человеку ленту 33-го под
 * хроникой 44-го, и он бы расхождения не заметил.
 *
 * ПОРЯДОК ОДИН: адрес → сохранённое → сервер сайта.
 *   Адрес важнее: его пишет человек, которому дали ссылку. Сохранённое важнее
 *   номера сайта: человек однажды сказал «мне нужен 44-й» и не обязан
 *   повторять это на каждой вкладке.
 *
 * ПОЧЕМУ ФУНКЦИИ ЧИСТЫЕ.
 *   Разбор здесь не знает ни DOM, ни `location`, ни `localStorage`: те же
 *   границы, что у `src/logic/standings.js` — строка адреса обязана дважды
 *   давать один и тот же результат, и проверить это надо без браузера. Чтение
 *   адреса делает вызывающий: у форума это `src/forum/mount.js`, у вкладок
 *   рейтинга — `src/ui/server-switch.js`.
 *
 * ИСКЛЮЧЕНИЕ ОДНО, И ОНО ЖИВЁТ ЗДЕСЬ СОЗНАТЕЛЬНО: пара readServerChoice /
 *   writeServerChoice трогает память браузера. Вынес её из вызывающих одна
 *   причина — выбор с этого шага общий, и две копии склейки с хранилищем
 *   разошлись бы тихо: форум помнил бы 44-й, а рейтинг читал бы свою память и
 *   молча показывал 33-й. Ключ и проверка числа тогда жили бы в двух файлах.
 *
 * ПОЧЕМУ ЧИСЛО МОЖЕТ ОКАЗАТЬСЯ `null`, И ЭТО НЕ ОДНАКО ЗНАЧИТ ДЛЯ ДВУХ СТОРОН.
 *   Для ленты форума `null` — «серверов не различаем»: фильтра в запросе нет, и
 *   до прогона миграции с колонкой это единственное, что форум не ломает.
 *   Для данных сайта `null` означает «сервер сайта»: набор без номера база
 *   отдаёт по значению по умолчанию. Поэтому здесь порядок заканчивается на
 *   памяти браузера, а чем его закончить — решает вызывающий.
 */

/** Ключ сервера в адресе: он же номер ряда таблицы `forum_servers`. */
export const SERVER_KEY = 'server';

/*
  Границы взяты из проверки колонки в базе (`id between 1 and 999`). Число вне
  них — не ошибка адреса, а «сервер не назван»: ссылка из старого разговора не
  обязана показывать пустой экран.
*/
export const SERVER_MIN = 1;
export const SERVER_MAX = 999;

/**
 * Ключ сохранённого выбора. Назван `zr33.server`, а не `zr33.forum.server`,
 * потому что выбор с этого шага один на весь сайт; прежний ключ не читаем
 * намеренно — это настройка просмотра, а не история, и потерянный один щелчок
 * стоит дешевле вечно живущей во лжи строки.
 */
export const SERVER_CHOICE_KEY = 'zr33.server';

/** Строка адреса → номер сервера или null, когда сервер в адресе не назван. */
export function serverFromSearch(search) {
  const raw = new URLSearchParams(String(search ?? '')).get(SERVER_KEY);
  if (raw == null || raw === '') return null;
  return serverInRange(raw);
}

/**
 * Адрес страницы целиком → сервер в его хвосте: `#/ladder?server=44`.
 *
 * Разделитель здесь тот же, что в разборе вкладок (`src/main.js`): хвост
 * начинается после «?». Отдельная функция потому, что до этого шага сервер
 * умели доставать только из хвоста, который кому-то передали, а данные сайта
 * спрашивают выбор сами — откуда его ещё не приносили.
 */
export function serverFromHash(hash) {
  const search = String(hash ?? '').split('?')[1];
  return search == null ? null : serverFromSearch(search);
}

/** Значение из памяти браузера → номер сервера или null. */
export function serverFromStored(raw) {
  if (raw == null || String(raw).trim() === '') return null;
  return serverInRange(raw);
}

/**
 * Сохранённый выбор сервера, или null, когда человек его никогда не делал.
 *
 * Отказ хранилища — не беда: лента и рейтинг просто стартуют без сохранённого
 * выбора. Ошибку сюда не поднимают ради того же порядка, что и в тихих часах:
 * настройка просмотра не может быть причиной пустого экрана.
 */
export function readServerChoice() {
  try {
    return serverFromStored(localStorage.getItem(SERVER_CHOICE_KEY));
  } catch {
    return null;
  }
}

/** Запомнить сервер; null — забыть и вернуться к серверу сайта. */
export function writeServerChoice(id) {
  try {
    if (id == null) localStorage.removeItem(SERVER_CHOICE_KEY);
    else localStorage.setItem(SERVER_CHOICE_KEY, String(id));
  } catch {
    /* Приватный режим: выбор действует до перезагрузки, и это честно. */
  }
}

/**
 * Адрес и память → выбранный сервер, или null, когда человек ничего не выбирал.
 * Порядок здесь — единственное место, где он записан: два вызывающих, решающих
 * его по-своему, однажды разошлись бы, и это тот редкий случай, где ошибка не
 * бросается в глаза — человек просто читал бы чужой сервер.
 */
export function resolveServer({ address = null, stored = null } = {}) {
  return address ?? stored ?? null;
}

/**
 * Сервер в хвост адреса.
 *
 * Дефолт не пишется по той же причине, что и «Все разделы»: ссылка на общий
 * сервер не должна выглядеть как ссылка на выбранный. Отдельная оговорка —
 * «значение названо»: `Number(null)` это ноль, и без неё пустой выбор уехал бы
 * в адрес как `server=0`, то есть ссылка на сервер, которого в таблице нет.
 *
 * Прежний ключ при этом вычищается: ряд в шапке меняет сервер у адреса, который
 * уже что-то содержит. Оставить старый `server=44`, когда человек щёлкнул
 * «свой» сервер, значило бы, что адрес спорит с памятью браузера, а адрес
 * важнее — и щелчок оказался бы несделанным.
 */
export function putServerParam(params, server, defaultServer) {
  const id = Number(server);
  if (server != null && Number.isInteger(id) && id !== Number(defaultServer)) {
    params.set(SERVER_KEY, String(id));
  } else {
    params.delete(SERVER_KEY);
  }
  return params;
}

/**
 * Заголовок вкладки выбранного сервера.
 *
 * Виден тому, у кого открыто десять вкладок, и по нему человек находит
 * нужный сервер, не разворачивая окно. Меняется только ведущая метка
 * («Сервер 33»), остальное название сайта остаётся как есть.
 */
export function serverTabTitle(baseTitle, title) {
  if (!title) return baseTitle;
  return String(baseTitle).replace(/^Сервер \d+/, String(title));
}

/**
 * Строка → номер сервера в границах таблицы, или null.
 *
 * Открыта нарочно: ряд в шапке читает номер из атрибута кнопки, и проверять его
 * тем же диапазоном, что адрес и память, — смысл этого модуля, а не деталь
 * разборщика адресов.
 */
export function serverInRange(raw) {
  if (raw == null || String(raw).trim() === '') return null;
  const id = Number(raw);
  return Number.isInteger(id) && id >= SERVER_MIN && id <= SERVER_MAX ? id : null;
}

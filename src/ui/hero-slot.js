import { CONFIG } from '../../config.js';

/**
 * Путь к картинке героя, который вписал владелец сайта.
 *
 * Пустая строка (а также пробелы вместо пути) означает, что картинки нет
 * вовсе, и тогда слой не рисуется совсем: ни `<img>`, ни запроса, ни пустой
 * рамки. Герой при этом не становится лысым — сетка, свечение и виньетка
 * живут в CSS и не зависят от файла.
 *
 * Общее место для этого вопроса нужно потому, что о наличии кадра знают двое:
 * сам герой (src/pages/home.js) и контур ожидания главной (src/ui/skeleton.js).
 * Контур резервует высоту героя вместе с полосой кадра; если бы он решал про
 * кадр сам и ошибся, страница подпрыгнула бы ровно в момент прихода данных.
 */
export function heroImage() {
  return String(CONFIG.hero?.image ?? '').trim();
}

/**
 * Подпись кадра. Пустая строка означает «декорация»: программа экрана пропустит
 * слой, и человек не будет слушать описание фона там, где ему нужны цифры.
 */
export function heroAlt() {
  return String(CONFIG.hero?.alt ?? '').trim();
}

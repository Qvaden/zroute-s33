/*
  Отзывчивые картинки: один ряд копий на весь сайт.

  Копии лежат рядом с оригиналом и называются по своей ширине:
  `…-560.webp`, `…-840.webp`, `…-1120.webp`, и те же ступени в `.avif`.
  Оригиналы не трогаются — их по-прежнему тянет браузер без WebP и AVIF
  и любой робот, который читает `src`.

  Имена копий задаёт правило, а не список: генератор, разметка и проверка в
  тестах вычисляют их из ширины оригинала одинаково. Поэтому «пообещали файл,
  которого нет на диске» ловит тест по факту файлов, а не внимание человека.

  ДВА ФОРМАТА В ОДНОМ РЯДУ — НЕ «НА ВЕРХ ФОРМАТА». AVIF добавлен по живому
  замеру (`scratch/avifprobe.mjs`, q=45 против WebP q=72 на 19 ступенях
  выборки): копия стабильно в 1,4–2 раза легче WebP той же ширины и легче
  оригинала. Ряд ширин при этом один на оба формата, и проверка требует,
  чтобы копия одного формата без копии другого на диске не лежала: иначе
  `<picture>` для части картинок предлагал бы формат, которого нет.

  Ширины ряда сняты живым замером (`scratch/imgw.mjs`), а не на глаз: рамка
  рисунка в справочнике — 270 px на экране 320 px, 340 на 390, 676 на 760,
  1096 на 1440 и 1126 на 1920. Верхняя ступень 1120 закрывает 1126 с запасом
  в шесть пикселов, нижняя 560 — телефон с DPR 2 (340 × 2 = 680 попадает в
  ступень 840, 270 × 2 = 540 — в 560).
*/

/** Ступени ряда копий, по возрастанию. Один ряд для WebP и для AVIF. */
export const WEBP_LADDER = [560, 840, 1120];

/** Сколько пикселов занимает рамка рисунка в статье — по тому же замеру. */
export const FIGURE_SIZES = '(min-width: 1400px) 1126px, (min-width: 760px) calc(100vw - 84px), calc(100vw - 50px)';

/** То же для кадра героя: 364 px на 390, 724 на 760, 1144 на 1440, 1174 на 1920. */
export const HERO_SIZES = '(min-width: 1400px) 1174px, calc(100vw - 26px)';

/**
 * Пути кадра героя, для которых копии есть на диске.
 *
 * Кадр владелец вписывает в `config.js` любой, а `<picture>` не откатывается
 * на `<img>`, если выбранный кандидат не нашёлся: картинка просто не
 * покажется. Поэтому герою копии обещаются только для файла из этого списка,
 * а для нового файла герой останется на оригинале, пока копии не сделаны.
 *
 * Список про оба формата: копия есть — значит есть и `.webp`, и `.avif`
 * на всех обещанных ступенях. Это держит проверка в тестах.
 */
export const HERO_WITH_COPIES = new Set(['./public/hero/oblika.jpg']);

/**
 * Ширины копий, которые должны существовать для оригинала шириной `w`.
 *
 * Ступень не берётся, если она шире оригинала: увеличивать картинку смысла
 * нет. Если оригинал уже всей лестницы, копия всё равно нужна — в ней формат
 * (WebP или AVIF вместо JPEG), и её ширина равна исходной.
 */
export function variantWidths(w) {
  const width = Number(w);
  if (!Number.isFinite(width) || width <= 0) return [];
  const list = WEBP_LADDER.filter((t) => t < width);
  if (width <= WEBP_LADDER[WEBP_LADDER.length - 1]) list.push(width);
  return [...new Set(list)].sort((a, b) => a - b);
}

/** Адрес копии для оригинала `path` на ступени `w`. */
export function variantPath(path, w, ext = 'webp') {
  return String(path).replace(/\.(jpe?g|png|webp)$/i, `-${w}.${ext}`);
}

/**
 * `srcset` для `<source type="image/webp">`.
 *
 * Пустая строка — копий нет, и `<picture>` рисовать не из чего: вызывающий
 * код тогда отдаёт обычный `<img>` без всякого `srcset`, то есть ровно то,
 * что было до этого шага.
 */
export function webpSrcset(path, w) {
  return srcsetFor(path, w, 'webp');
}

/** `srcset` для `<source type="image/avif">` — тот же ряд, другое расширение. */
export function avifSrcset(path, w) {
  return srcsetFor(path, w, 'avif');
}

function srcsetFor(path, w, ext) {
  return variantWidths(w).map((t) => `${variantPath(path, t, ext)} ${t}w`).join(', ');
}

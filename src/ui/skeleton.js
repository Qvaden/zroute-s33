/*
  Контур живой страницы.

  Живой раздел приезжает не сразу: запрос в базу идёт секунды, и всё это время
  под шапкой висела одна строчка «Загружаем…». Когда ответ приходил, на её место
  вставал список в двести строк — документ делался выше на два экрана, и подвал
  вместе с шапкой подскакивал. На телефоне это повторяется на каждой вкладке и
  выглядит как «сайт дёргается».

  Здесь вместо строчки рисуется контур будущего списка: столько же карточек, те
  же высоты, никаких слов. Настоящие карточки встанут ровно в эти рамки, поэтому
  длина страницы при приходе данных почти не меняется.

  Высоты заданы стилями (классы sk- в src/refine.css), а не числами здесь:
  подгонять контур удобнее рядом с теми же карточками, чью высоту он повторяет.
*/

import { heroImage } from './hero-slot.js';

/** Три полоски-строки: текст ещё не пришёл, но его место видно. */
function lines(count) {
  return `<span class="sk__lines">${'<i class="sk__line"></i>'.repeat(count)}</span>`;
}

/** n групп по k полосок: ряды рейки, хвост рейтинга, список обсуждений. */
function rows(n, k = 2) {
  return Array.from({ length: n }, () => lines(k)).join('');
}

/** Полоска там, где у живой панели стоит eyebrow с названием раздела. */
const HEAD = '<i class="sk__line sk__line--head"></i>';

/**
 * Две колонки внутри рамки — как живой ряд из двух панелей.
 * Доли задаёт refine.css по тем же брейкпоинтам, что и сама сводка:
 * контур обязан складываться в колонки ровно там, где складывается ряд,
 * иначе на телефоне он резервирует высоту одного столбца, а данные приедут
 * двумя, и рамка окажется вдвое короче списка.
 */
function cols(a, b) {
  return `<div class="sk__cols"><div class="sk__col">${a}</div><div class="sk__col">${b}</div></div>`;
}

/**
 * Пять рамок главной — ровно те пять блоков, что рисует сводка:
 * герой, панель «Прямо сейчас», ряд рейки с летописью, обсуждения во всю
 * ширину и «Движение в рейтинге».
 *
 * Про порядок. Он повторяет src/pages/home.js: герой → «сейчас» → «кто
 * ведёт» → «чем жил сервер» → «движение за неделю». Стоит переставить
 * рамку, и высоты перестанут относиться к своим местам.
 *
 * Про четвёртую рамку. Раньше она была двухколоночной: обсуждения стояли в
 * ряду с гоночным графиком. График уехал вниз «Рейтинга» (src/pages/ladder.js,
 * racePanel), и в ряду осталась одна панель, которую растягивает *:only-child,
 * — значит контур обязан быть одноголосым: две колонки в рамке резервировали
 * бы высоту, которой на странице больше нет. Имя рамки — --comm, а не --back:
 * «заднего ряда» не стало, и называть рамку должен её блок, а не место в ряду.
 *
 * Про состав полосок. Числа взяты из живого же рендера, а не на глаз:
 * у рейки трое в подиуме и четверо в хвосте, у летописи один большой
 * разбор и две записи покороче, в обсуждениях всегда четыре темы (это
 * резерв самого слота, см. renderCommunitySlot), у «движения» по три
 * строки в каждой из колонок.
 */
const OPS = [
  () => `<div class="sk__card sk__card--ops${heroImage() ? ' sk__card--ops--art' : ''}"><div class="sk__ops">`
    + '<i class="sk__line sk__line--title"></i>'
    + `${lines(2)}</div><div class="sk__side">${lines(3)}</div>`
    + '<div class="sk__bars"><i class="sk__line"></i><i class="sk__line"></i><i class="sk__line"></i></div></div>',
  () => `<div class="sk__card sk__card--live">${HEAD}${cols(lines(3), lines(3))}</div>`,
  () => `<div class="sk__card sk__card--lead">${cols(`${HEAD}${rows(3)}${rows(4, 1)}`,
    `${HEAD}${lines(3)}${rows(2)}`)}</div>`,
  () => `<div class="sk__card sk__card--comm">${HEAD}${rows(4)}</div>`,
  () => `<div class="sk__card sk__card--move">${cols(`${HEAD}${rows(3, 1)}`, `${HEAD}${rows(3, 1)}`)}</div>`,
];

/**
 * Один блок контура.
 * kind:
 *   post — аватар и текст: лента форума, страница участника;
 *   card — карточка с абзацем: заметки обновлений, дни календаря;
 *   row  — компактная строка: список гайдов;
 *   tile — плитка: доска аккаунтов;
 *   ops  — сводка главной: пять рамок по списку OPS, а не один размер на
 *          все карточки.
 *
 * Про 'ops' отдельно. Обычный контур из одинаковых карточек резервирует
 * высоту списка, а главная — список из разных по росту блоков: герой на весь
 * первый экран, панель «Прямо сейчас» на 180 px, ряд рейки с летописью на
 * 553, обсуждения во всю ширину на 300 и «движение» на 248 — замер при
 * окне 1361×900. Пять рамок по 190 px подгоняли под среднее, а не под каждый
 * блок, и в момент прихода данных страница дорастала на полтора экрана.
 * Сумму резерва против живой страницы сравнивает не этот комментарий, а
 * прогон CLS: tools/walk.mjs идёт по вкладкам и называет цифрами, кто и на
 * сколько сдвинулся.
 *
 * Высота героя зависит от окна и от полосы кадра, поэтому резерв в refine.css
 * — не одно число, а та же формула, что у живого героя. Класс --art на первой
 * карточке появляется только когда путь к картинке в config.js непустой: без
 * него резерв не должен хранить место под кадр, которого не будет.
 */
function block(kind, index) {
  if (kind === 'post') return `<div class="sk__card"><span class="sk__ava"></span>${lines(3)}</div>`;
  if (kind === 'row') return `<div class="sk__card">${lines(2)}</div>`;
  if (kind === 'tile') return '<div class="sk__card"></div>';
  if (kind === 'ops') return (OPS[index] ?? OPS[OPS.length - 1])();
  return `<div class="sk__card">${lines(2)}</div>`;
}

/**
 * Готовый контур на n блоков.
 *
 * aria-hidden — контур не содержимое, а ожидание: программа экрана не должна
 * пересчитывать пустые рамки. Сказ о том, что грузится, остаётся в подписи,
 * которую вызывающая страница печатает сама.
 */
export function skeleton(kind, n = 4) {
  const list = Array.from({ length: Math.max(1, n) }, (_, index) => block(kind, index)).join('');
  return `<div class="sk sk--${kind}" aria-hidden="true">${list}</div>`;
}

/** Подпись над контуром: то же слово, что стояло на этом месте раньше. */
export function skWithCaption(caption, kind, n = 4) {
  return `<p class="sk__caption">${caption}</p>${skeleton(kind, n)}`;
}

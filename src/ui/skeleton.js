/*
  Контур живой страницы.

  Живой раздел приезжает не сразу: запрос в базу идёт секунды, и всё это время
  под шапкой висела одна строчка «Загружаем…». Когда ответ приходил, на её место
  вставал список в двести строк — документ делался выше на два экрана, и подвал
  вместе с шапкой подскакивал. На телефоне это повторяется на каждой вкладке и
  выглядит как «сайт дёргается».

  Здесь вместо строчки рисуется контур будущего списка: столько же карточек, те
  же высоты, никаких слов. Настоящие карточки встанут ровно в эти рамки, поэтому
  длина страницы при приходе данных почти не меняется.

  Высоты заданы стилями (классы sk- в src/refine.css), а не числами здесь:
  подгонять контур удобнее рядом с теми же карточками, чью высоту он повторяет.
*/

import { heroImage } from './hero-slot.js';

/** Три полоски-строки: текст ещё не пришёл, но его место видно. */
function lines(count) {
  return `<span class="sk__lines">${'<i class="sk__line"></i>'.repeat(count)}</span>`;
}

/**
 * Один блок контура.
 * kind:
 *   post — аватар и текст: лента форума, страница участника;
 *   card — карточка с абзацем: заметки обновлений, дни календаря;
 *   row  — компактная строка: список гайдов;
 *   tile — плитка: доска аккаунтов;
 *   ops  — командный центр главной: первым блоком герой с колонкой панели
 *          источника, остальное — карточки, которые идут под ним.
 *
 * Про 'ops' отдельно. Обычный контур из одинаковых карточек резервирует
 * высоту списка, а первая настоящая карточка главной — герой во весь первый
 * экран, и под ним ещё панель на 176 px. Без такой же рамки в контуре
 * страница сдвигалась бы на полэкрана ровно в момент прихода данных.
 *
 * Высота героя зависит от окна и от полосы кадра, поэтому резерв в refine.css
 * — не одно число, а та же формула, что у живого героя. Класс --art на первой
 * карточке появляется только когда путь к картинке в config.js непустой: без
 * него резерв не должен хранить место под кадр, которого не будет.
 */
function block(kind, index) {
  if (kind === 'post') return `<div class="sk__card"><span class="sk__ava"></span>${lines(3)}</div>`;
  if (kind === 'row') return `<div class="sk__card">${lines(2)}</div>`;
  if (kind === 'tile') return '<div class="sk__card"></div>';
  if (kind === 'ops' && index === 0) {
    return `<div class="sk__card sk__card--ops${heroImage() ? ' sk__card--ops--art' : ''}"><div class="sk__ops">`
      + '<i class="sk__line sk__line--title"></i>'
      + `${lines(2)}</div><div class="sk__side">${lines(3)}</div>`
      + '<div class="sk__bars"><i class="sk__line"></i><i class="sk__line"></i><i class="sk__line"></i></div></div>';
  }
  return `<div class="sk__card">${lines(2)}</div>`;
}

/**
 * Готовый контур на n блоков.
 *
 * aria-hidden — контур не содержимое, а ожидание: программа экрана не должна
 * пересчитывать пустые рамки. Сказ о том, что грузится, остаётся в подписи,
 * которую вызывающая страница печатает сама.
 */
export function skeleton(kind, n = 4) {
  const list = Array.from({ length: Math.max(1, n) }, (_, index) => block(kind, index)).join('');
  return `<div class="sk sk--${kind}" aria-hidden="true">${list}</div>`;
}

/** Подпись над контуром: то же слово, что стояло на этом месте раньше. */
export function skWithCaption(caption, kind, n = 4) {
  return `<p class="sk__caption">${caption}</p>${skeleton(kind, n)}`;
}

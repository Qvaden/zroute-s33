/*
  Короткое сообщение сайта — один помощник, а не две копии.

  Полосу показывают два модуля форума: чат отвечает на кнопки («Ссылка
  скопирована», «Чат удалён навсегда»), лента — на ошибки базы и на
  отправленную жалобу. Каждый лепил её шестью своими строками, и копии
  разошлись ровно там, где у блока должно быть одно поведение:

  — чат перед показом убирал прежнюю полосу, лента нет. Обе позиции fixed
    и стоят в одной точке (`bottom` + `left: 50%`), поэтому два сообщения
    из ленты печатались друг на друге;
  — чат прятал полосу через 2600 мс, лента через 4000. Разница держалась
    не на решении, а на двух разных авторах: за это время надо успеть
    прочитать и «Откреплено», и двухстрочный отказ базы.

  Отсюда `ms` считается от длины текста: короткое подтверждение живёт
  2600 мс, длинная ошибка — до 5000. Число не щедрость: полоса перекрывает
  контент, и держать её дольше, чем нужно для прочтения, значит воровать
  у человека нижний край экрана.

  Полоса, а не `alert`: последний останавливает страницу и на телефоне
  выглядит как ошибка сайта.

  ТОН — ВТОРОЙ АРГУМЕНТ, И ОН ОБЯЗАТЕЛЬНЫЙ. `error` ставит каждый отказ (база
  не приняла, браузер не смог, файл не влез), `warn` — то, что случилось, но с
  последствиями, о которых надо знать: отключённые push, сменённый код, запрет,
  остающийся на время разбора апелляции, `ok` — что действие удалось.

  Значение по умолчанию убрано не ради строгости, а из-за полосы 19.10: когда
  тон можно не называть, забытый тон молча становится зелёным, и отказ базы
  выглядит успехом. Теперь пропущенный аргумент — падение проверки BE, а не
  цвет на глаз. Вызывающий код по-прежнему не знает ни одной краски: имена тона
  раскрашивает forum.css, поэтому светлая тема приносит свои чернила.
*/

export function toast(message, kind) {
  const text = String(message ?? '');
  document.querySelector('.forum-toast')?.remove();
  const box = document.createElement('div');
  box.className = kind === 'ok' ? 'forum-toast' : `forum-toast forum-toast--${kind}`;
  box.textContent = text;
  document.body.append(box);
  window.setTimeout(() => box.remove(), Math.min(5000, Math.max(2600, Math.round(text.length * 60))));
}

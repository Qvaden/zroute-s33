-- 2026-09-26. Тихие часы: телефон молчит ночью, лента — нет.
--
-- Пункт пришёл с большого форума сообщества (Qvaden/zroute-alliance-hub): там
-- у игрока есть окно «не показывать системные оповещения браузера». Перенесено
-- ровно то, что у нас работает: решение принимает сам браузер, а не сервер.
--
-- ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
--
-- Push — единственная вещь на сайте, которая доходит до человека сама. Дайджест,
-- напоминание о встрече и все триггеры лишь кладут строку в ленту колокольчика,
-- а её человек читает, когда сам открыл сайт. Пуш приходит в карман в три часа
-- ночи, и от этого его никто не просил: сообщение альянса подождёт до утра,
-- а разбуженный человек — нет.
--
-- Без правила выбор был один — выключать push целиком и терять день. Тихие
-- часы оставляют подписку включённой и убирают только шум в то время, когда
-- человек спит.
--
-- ── ПРАВИЛО ─────────────────────────────────────────────────────────────────
--
--   1. Окно задаётся двумя границами в минутах от полуночи (0…1439). Строка
--      либо с обеими границами, либо без обеих: «начало есть, конца нет» —
--      это не тихие часы, а незаполненная форма.
--   2. Окно через полночь — норма, а не ошибка: 22:00 → 08:00 значит «тихо
--      сейчас с 22 до полуночи и с полуночи до 8».
--   3. Совпавшие границы — отказ. Молчать весь день — не тихие часы, а
--      выключенные уведомления; для этого у игрока есть тумблеры подписки.
--   4. Внутри окна оповещение не показывается. Строка уведомления в ленте при
--      этом стоит с того самого момента, как появилась: правило ничего не
--      откладывает, не накапливает и не досылает утром.
--   5. Вне окна и при любой неизвестности (окно не прочиталось, хранилище
--      браузера недоступно, в границах мусор) — показываем. Тишину, которую
--      нельзя объяснить, человек заметит позже, чем шум.
--
-- ── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ────────────────────────────────────────────────
--
-- Часового пояса. У донора окно пересчитывает сервер в UTC, поэтому ему нужна
-- IANA-зона игрока, её выбор из списка и отказ на неверном имени. У нас
-- решение принимает браузер, а его локальное время и есть «ночь этого
-- человека»: переехал в другой город — тишина поехала вместе с ним, ничего
-- не надо переключать.
--
-- Белого списка срочных. Донор пропускает упоминания, ответы и сигналы
-- безопасности. Нам пропускать нечего: личных каналов у нас нет (комнаты
-- альянсов и межальянсовая), а предупреждения, запреты и разборы жалоб живут
-- в ленте и в пуш не попадают никогда.
--
-- Отложенной доставки. Она потребовала бы очереди и второго запуска рассылки
-- утром — серверной части у нас нет вовсе, а бесплатные лимиты очередь съела бы
-- первой.
--
-- Тишины для ленты. Колокольчик не будит: он молчит, пока человек не зашёл.
--
-- ── КТО РЕШАЕТ И ГДЕ ЖИВЁТ ЗНАЧЕНИЕ ────────────────────────────────────────
--
-- Значение живёт здесь, рядом с остальными push-подписками, — чтобы настройка
-- не исчезала при очищенных данных сайта и доезжала до второго устройства,
-- когда игрок зашёл туда под своим ником. Читает её фронт (`getPushPrefs`)
-- и перекладывает в IndexedDB того же браузера: сервисный работник, который
-- показывает пуш при закрытой вкладке, `localStorage` не видит.
--
-- `send-push` про эти колонки не знает намеренно. Ему незачем гадать, где
-- сейчас ночь игрока, а доставка всё равно считается состоявшейся: оповещение
-- дошло до браузера и уже там решает, будить или нет. Тот же приём у донора:
-- «несрочные оповещения браузера не показываются, уведомления остаются в
-- личной ленте».
--
-- Дверей (`security definer`) здесь нет ни одной: у таблицы уже есть политики,
-- по которым владелец строки пишет сам себя, а модерация видит настройки
-- игроков — это нужно для честного ответа на «почему мне не пришла подсказка».
--
-- ── ЧИСЛА ───────────────────────────────────────────────────────────────────
--
-- Диапазон границ (0…1439) и значения по умолчанию новой настройки (22:00 и
-- 08:00) продублированы в `config.js` (`quietMinutesMax`, `quietDefaultStart`,
-- `quietDefaultEnd`) — совпадение сторожит тест. Здесь, в проверке колонки,
-- число обязано быть всё равно: браузер можно обойти, а базу нет.
--
-- ── ЗАПУСК ──────────────────────────────────────────────────────────────────
--
-- Один раз, Supabase → SQL Editor → Run. Таблиц и крон-задач не появляется:
-- две колонки у уже существующей таблицы настроек.
--
-- До пуша кода миграция не обязательна, но желательна: без колонок форум читает
-- и пишет push-подписки как читал, а окно сохранить не даст — база скажет, что
-- такой колонки нет. Ошибки на странице из-за этого не появится.

alter table public.forum_push_prefs
  add column if not exists quiet_start smallint,
  add column if not exists quiet_end   smallint;

comment on column public.forum_push_prefs.quiet_start is
  'Минут от полуночи в начале тихих часов (0…1439); null — окно не задано. Считает браузер игрока, не сервер.';
comment on column public.forum_push_prefs.quiet_end is
  'Минут от полуночи в конце тихих часов; раньше начала — это нормально, окно через полночь. Равное началу запрещено: молчать круглые сутки — не настройка, а выключенный push.';

-- Проверка переобъявляется, чтобы повторный запуск файла не оставлял старых
-- границ: имя у неё своё, и тест сверяет именно его.
alter table public.forum_push_prefs
  drop constraint if exists forum_push_prefs_quiet_window;

alter table public.forum_push_prefs
  add constraint forum_push_prefs_quiet_window check (
    (quiet_start is null and quiet_end is null)
    or (
      quiet_start is not null
      and quiet_end is not null
      and quiet_start between 0 and 1439
      and quiet_end between 0 and 1439
      and quiet_start <> quiet_end
    )
  );

-- 2026-09-26. Сигналы о спаме: модерация видит, кто сидит на пределе выдержки.
--
-- Пункт очереди, перенесённый с форума сообщества (Qvaden/zroute-alliance-hub),
-- где он называется «журнал сигналов о спаме».
--
-- ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
--
-- Выдержка уже держит поток: три темы за двадцать минут, восемь ответов за две,
-- запрет повторять свой текст. Она отказывает человеку в лицо и на этом
-- замолкает. Модерация ничего не узнаёт: в панели нет ни списка тех, кто
-- упирается в предел, ни намёка на то, что кто-то бился в отказ десять раз
-- подряд. Решение о тишине принимается вслепую — по одной жалобе, про которую
-- кто-то рассказал в чате.
--
-- Здесь модератору показывают тех, кого уже видно по данным форума: кто сел на
-- предел выдержки, чьи материалы облепили жалобами, что уже скрылось после
-- пяти. Это не второй надзиратель, а лупа над тем, что и так лежит в таблицах.
--
-- ── ПОЧЕМУ НЕ ЖУРНАЛ ────────────────────────────────────────────────────────
--
-- У донора этот пункт — таблица `moderationSpamSignals`: её пишет сервер
-- (Node/tRPC) перед тем, как бросить ошибку «выдержка». Сервер успевает
-- зафиксировать факт отдельной транзакцией, а потом отказать.
--
-- Нас записывать отказ некому. Он живёт в триггере `forum_posts_hold` и
-- поднимает исключение. Любая строка, вставленная в том же вызове до
-- `raise exception`, откатывается вместе с ним: в Postgres нет автономной
-- транзакции, а сервера между браузером и базой у нас нет. Получился журнал,
-- который всегда пуст, — худший из возможных вариантов, потому что пустой
-- список читается как «спама нет».
--
-- Оставался второй путь: пусть браузер сам докладывает о полученном отказе.
-- Отказались осознанно: такой сигнал пишет только честный клиент. Самописный
-- бот его не шлёт вовсе, а злой человек зальёт им кого угодно — и в журнал
-- модерации попадёт то, что никто не проверял. У остального форума правило
-- другое: автора строки берём из токена, а не из тела запроса, — и здесь оно
-- не работает, потому что тело запроса как раз и есть чужие слова.
--
-- Поэтому переносим не форму (таблицу отказов), а смысл: сигнал о спаме — это
-- то, что база может увидеть сама. Отказы скрыть нельзя, зато нельзя и
-- выдумать темп, с которым человек пишет. Строки, которые он реально оставил,
-- и есть честный сигнал.
--
-- ── ПРАВИЛО ─────────────────────────────────────────────────────────────────
--
--   1. Список вычисляется на каждом запросе и ничего не хранит. Захотелось
--      глянуть вчера — вчерашнего там нет; окно короткое ровно затем, чтобы
--      показывать живое, а не состав за прошлую неделю.
--   2. Причина попасть в список одна из трёх: предел выдержки рядом (до отказа
--      осталась одна запись), две открытые жалобы на материалы человека, либо
--      его материал уже скрылся после пяти жалоб.
--   3. Запрет писать и тишина показаны, но причиной не являются: это уже
--      принятое решение, а не сигнал. Модератор видит колонки запрета рядом и
--      не заводит дело на того, кого уже приостановил.
--   4. Порога автоматического действия нет. Ничего не скрывается, не
--      замораживается и не уведомляется по попаданию в список. Сигнал — это
--      «посмотри», а не «наказано».
--   5. Список читает только модерация, и человек не узнаёт, что он в списке.
--      Публичный рейтинг подозрений превратился бы в игру: держаться ровно на
--      одну тему ниже предела, чтобы «не засветиться».
--   6. Убран из списка тот, у кого нет ни тем, ни ответов за сутки: пустая
--      строка с нулями ничего не объясняет, а жалобу без активности разберут
--      в очереди жалоб, где ей и место.
--
-- ── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ────────────────────────────────────────────────
--
--   Оценки в баллах. Донор хранит `score` от 30 до 100 и суммирует его. У нас
--   нет сервера, который честно посчитал бы веса, и нет людей, которые
--   согласятся с чужой арифметикой: «шесть сигналов» и «шесть жалоб» — разные
--   истории, а в балле они неразличимы. Модератор видит отдельные числа.
--
--   Правил по ключевым словам (донорский `moderationKeywordRules`). Слово в
--   тексте не делает запись спамом, а список запрещённых слов на маленьком
--   форуме становится тем, о чём спорят больше, чем о спаме.
--
--   Истории. Раз список вычисляется, копить прошлое негде — и не нужно:
--   прошлое уже лежит в темах и ответах, а журнал решений ведёт
--   `forum_moderation_actions`.
--
--   Уведомлений игроку. «Тебя заметили» без решения по существу — это запугивание.
--
-- ── ПОЧЕМУ ФУНКЦИЯ, А НЕ ПРЕДСТАВЛЕНИЕ ──────────────────────────────────────
--
--   Представление с `security_invoker = on` отдаёт то, что пропускают политики
--   соседних таблиц: темы и ответы читают все, поэтому список «кого подозревают»
--   достался бы и гостю — а это ровно то, чего правило 5 не допускает. Дверь
--   `security definer` проверяет роль один раз и отвечает внятным отказом, а не
--   пустым ответом, из которого не понять, пусто ли на форуме или тебе не видно.
--
--   Данных здесь никто не пишет: таблица не нужна, строку не создашь, не
--   изменишь и не удалишь. Поэтому миграция состоит из одной функции и ничего
--   не меняет в существующих таблицах — застывания колонок и пересоздания
--   представлений здесь нет.
--
-- ── ЧИСЛА ───────────────────────────────────────────────────────────────────
--
--   Окна выдержки (20 минут и 2 минуты) и пределы (3 темы и 8 ответов, модерации
--   — втрое больше) взяты из `20260925-spam-hold-and-topic-reads.sql` один в
--   один. Смысл сигнала «предел рядом» = `разрешено - 1`: человек ещё может
--   писать, но следующий шаг упрётся в отказ. Те же значения лежат в
--   `config.js` (`postHoldMax`, `commentHoldMax`, `spamSignalReportMin`,
--   `spamSignalWindowDays`), а совпадение чисел и текст отказа сторожит тест.
--   Увеличить окно в базе, не тронув выдержку, — значит сделать сигнал враньём;
--   поэтому тест сверяет их друг с другом, а не с константой.
--
--   Неделя (7 дней) одна на два факта: открытая жалоба старше недели и скрытый
--   неделю назад материал — это не живой сигнал, а забытая отметка. Разводить
--   их по разным окнам смысла нет: модератор читает строку целиком.
--
-- ── ЗАПУСК ──────────────────────────────────────────────────────────────────
--
-- Supabase → SQL Editor → вставить целиком → Run. Скрипт повторный: недостающее
-- создаёт, существующее правит. Порядок установки произвольный: функция ничего
-- не пишет и чужих таблиц не касается, ей нужны только таблицы форума из
-- `schema.sql` и поздних миграций — `forum_section_mutes` (20260925-section-mute)
-- и колонки `auto_hidden`/`deleted_at` (20260916-forum-community). Новых слов в
-- проверке `kind` уведомлений не появляется: сигналы никому не рассылаются. До
-- пуша кода миграция не обязательна: панель читает сигналы отдельным запросом и
-- без функции показывает, что список недоступен, а не пустой список.

-- ── Шаг 1. Сигналы ──────────────────────────────────────────────────────────

create or replace function public.forum_spam_signals()
returns table (
  user_id       uuid,
  nick          text,
  role          text,
  posts_20m     integer,
  comments_2m   integer,
  posts_24h     integer,
  comments_24h  integer,
  open_reports  integer,
  auto_hidden   integer,
  section_mutes integer,
  banned        boolean,
  muted_until   timestamptz,
  last_activity timestamptz,
  signals       text[]
)
language plpgsql
security definer
set search_path = public
as $$
#variable_conflict use_column
begin
  if not public.forum_is_staff() then
    raise exception 'Сигналы о спаме видит модерация'
      using errcode = 'insufficient_privilege';
  end if;

  return query
  with
  -- Темы за сутки: короткое окно выдержки и суточный масштаб одним проходом.
  pace as (
    select author_id as uid,
           count(*) filter (where created_at > now() - interval '20 minutes') as p20,
           count(*) as p24,
           max(created_at) as last_p
      from public.forum_posts
     where created_at > now() - interval '24 hours'
       and author_id is not null
     group by author_id
  ),
  -- Ответы за сутки: то же самое, но в двухминутном окне.
  cpace as (
    select author_id as uid,
           count(*) filter (where created_at > now() - interval '2 minutes') as c2,
           count(*) as c24,
           max(created_at) as last_c
      from public.forum_comments
     where created_at > now() - interval '24 hours'
       and author_id is not null
     group by author_id
  ),
  -- Открытые жалобы на материалы человека. Жалоба висит на посте или ответе,
  -- поэтому автор берётся из той записи, а не из жалобы: жалующийся тут —
  -- свидетель, а не подозреваемый.
  rep as (
    select x.uid, count(*) as n from (
      select p.author_id as uid
        from public.forum_reports r
        join public.forum_posts p on p.id = r.target_id
       where r.resolved = false and r.target_type = 'post'
         and r.created_at > now() - interval '7 days'
      union all
      select c.author_id
        from public.forum_reports r
        join public.forum_comments c on c.id = r.target_id
       where r.resolved = false and r.target_type = 'comment'
         and r.created_at > now() - interval '7 days'
    ) x where x.uid is not null group by x.uid
  ),
  -- То, что уже скрылось автоматом. Семь дней — не окно активности, а срок,
  -- за который «скрыто после жалоб» ещё стоит считать свежим фактом: раньше
  -- модератор обязан был отреагировать, и висящая отметка старше этого срока
  -- значит только одно — её забыли снять.
  hid as (
    select x.uid, count(*) as n from (
      select author_id as uid from public.forum_posts
       where auto_hidden = true and deleted_at > now() - interval '7 days'
      union all
      select author_id from public.forum_comments
       where auto_hidden = true and deleted_at > now() - interval '7 days'
    ) x where x.uid is not null group by x.uid
  ),
  mut as (
    -- Активные тишины по разделам. Имя колонки названо таблицей, а не просто
    -- `user_id`: так запрос читается одинаково и сегодня, и после того, как у
    -- списка появятся свои колонки с теми же именами.
    select sm.user_id as uid, count(*) as n
      from public.forum_section_mutes sm
     where sm.muted_until > now()
     group by sm.user_id
  ),
  ids as (
    select uid from pace
    union select uid from cpace
    union select uid from rep
    union select uid from hid
  ),
  base as (
    select u.id as uid,
           u.nick as nick,
           u.role as role,
           u.banned as banned,
           u.muted_until as muted_until,
           coalesce(p.p20, 0) as posts_20m,
           coalesce(c.c2, 0) as comments_2m,
           coalesce(p.p24, 0) as posts_24h,
           coalesce(c.c24, 0) as comments_24h,
           coalesce(r.n, 0) as open_reports,
           coalesce(h.n, 0) as auto_hidden,
           coalesce(m.n, 0) as section_mutes,
           -- Кто сколько пишет, модерация решает по месту; окно выдержки
           -- здесь только одно: staff получает втрое больше и седьмая тема
           -- к полуночи для него не сигнал, а работа.
           case when u.role in ('admin', 'moderator') then 9 else 3 end as posts_allowed,
           case when u.role in ('admin', 'moderator') then 24 else 8 end as comments_allowed,
           greatest(p.last_p, c.last_c) as last_activity
      from ids i
      join public.forum_users u on u.id = i.uid
      left join pace p on p.uid = u.id
      left join cpace c on c.uid = u.id
      left join rep r on r.uid = u.id
      left join hid h on h.uid = u.id
      left join mut m on m.uid = u.id
  ),
  marked as (
    select b.*,
           array_remove(array[
             case when b.posts_20m >= b.posts_allowed - 1
                  then 'темы на пределе выдержки' end,
             case when b.comments_2m >= b.comments_allowed - 1
                  then 'ответы на пределе выдержки' end,
             case when b.open_reports >= 2
                  then 'открытые жалобы на его материалах' end,
             case when b.auto_hidden >= 1
                  then 'материалы скрыты после пяти жалоб' end
           ], null) as sigs
      from base b
  )
    select m.uid,
           m.nick,
           m.role,
           m.posts_20m,
           m.comments_2m,
           m.posts_24h,
           m.comments_24h,
           m.open_reports,
           m.auto_hidden,
           m.section_mutes,
           m.banned,
           m.muted_until,
           m.last_activity,
           m.sigs
      from marked m
     -- Сигнал есть и человек пишет: без тем и ответов за сутки строки не бывает,
     -- даже если на неё висят жалобы. Так правило 6 не расходится с кодом.
     where cardinality(m.sigs) > 0
       and m.posts_24h + m.comments_24h > 0
     order by cardinality(m.sigs) desc, m.posts_24h + m.comments_24h desc, m.nick;
end;
$$;

comment on function public.forum_spam_signals() is
  'Сигналы о спаме для модерации: кто у предела выдержки, у кого жалобы и скрытое. Вычисляется на запрос, ничего не хранит.';

-- ── Шаг 2. Двери ────────────────────────────────────────────────────────────

/*
  Функция читает таблицы в обход политик (её автор — владелец), поэтому право
  исполнения и есть единственная дверь. Роль отдаём только вошедшим: гостю
  смотреть не на что, а отказ должен называть причину, а не «404».
*/
revoke all on function public.forum_spam_signals() from public, anon;
grant execute on function public.forum_spam_signals() to authenticated;

-- 2026-09-26. Пульс обновлений игры: заметки, которые руками кладёт модерация.
--
-- Идея пришла из большого форума сообщества (Qvaden/zroute-alliance-hub),
-- перенесена на наш SQL: там заметка — отдельная таблица, и у нас так же.
--
-- ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
--
-- Игра меняется чаще, чем об этом договариваются на форуме. Игрок узнаёт
-- перемену из официального объявления, пересказывает её в теме, и через вечер
-- в ленте три версии одного патча: одна с датой на два дня позже, вторая без
-- ссылки, третья «а мне сказали». Спорить с этим бесполезно — каждый пересказ
-- живёт своей жизнью.
--
-- Пульс закрывает вопрос «что вообще изменилось и когда» одним списком,
-- собранным модерацией: короткая заметка, тип (патч, объявление, известная
-- проблема), дата самого первоисточника и ссылка на него. Человек, который
-- пришёл с вопросом «это у меня ломается или после обновления?», видит ответ
-- до того, как напишет тему, а дежурный по форуму перестаёт переписывать одно
-- и то же в пяти темах.
--
-- ── ПОЧЕМУ ТАБЛИЦА, А НЕ МЕТКА ТЕМЫ ─────────────────────────────────────────
--
-- Календарь и обмен мы сделали метками темы, и это сработало: и встреча, и
-- объявление обмена — по форме обычный пост, у него есть автор, текст и
-- комментарии, где договариваются. Заметка об обновлении — не пост.
--
-- У неё нет своего обсуждения (комментарии под пересказом патча только
-- размножают версии, а для разговора на форуме есть темы), у неё есть чужая
-- дата — момент, когда вышло объявление на стороне разработчиков, а не момент,
-- когда её положил сюда модератор, и у неё есть состояние «в архиве», которого
-- у темы нет: патч переживают, а заметка о нём остаётся висеть в ленте и через
-- месяц, уже не как ответ на вопрос, а как память.
--
-- Меткой это не выразить: метка ничего не обязывает называть. Здесь же ссылка
-- на первоисточник и его дата обязательны самой базой.
--
-- ── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ────────────────────────────────────────────────
--
--   Автоматического чтения чужих страниц. У сайта нет серверной части, и
--   запрос к официальному сайту из браузера посетителя — это чужой текст без
--   проверки, который к тому же ломается при первом же изменении у них.
--   Заметку пишет человек, и отвечает за неё человек.
--
--   Перевод. Переведённый без живой редакции анонс патча — то же самое, что
--   пересказ: «nerf» превращается в «ослабление», а вместе с ним исчезает то,
--   что именно ослабили. Читатель видит название первоисточника и ссылку.
--
--   Правки после публикации. Заметка — датированное свидетельство о том, что
--   было написано у первоисточника; текст, который можно переписать молча,
--   перестаёт им быть. Ошиблись — в архив и новую.
--
--   Голосов, реакций и уведомлений на каждую заметку. Патчей несколько за
--   неделю: будить ими всех значило бы приучать не открывать колокольчик.
--   Заметка стоит в меню, а разговор о ней — на форуме, как о любом другом
--   событии игры.
--
-- ── ПРАВИЛО ─────────────────────────────────────────────────────────────────
--
--   1. Заметку публикует и убирает только модерация (admin или moderator по
--      строке аккаунта). Игрок список читает, но не пишет: пульс — это
--      ответ, а не раздел для мнений, и править его должен тот, кто отвечает
--      перед сервером.
--   2. Тип обязателен и выбирается из трёх слов. Свободное название типа
--      развалило бы список на «Патч», «Патч 1.4», «патчик» и «изменения».
--   3. Заголовок — от 6 и не больше 120 символов, содержание — от 20 и не
--      больше 1500. Нижний порог содержания не придирка: «обновили игру» —
--      это заголовок, а не заметка, и второй абзац под ним нечем заполнить.
--   4. Название первоисточника обязательно (от 2 до 60 символов) и ведёт на
--      него прямая HTTPS-ссылка. Ссылка обязана начинаться с https:// и не
--      содержать пробелов: её проверяет база, а не только форма.
--   5. Дата первоисточника обязательна, не из будущего (запас 10 минут — на
--      расхождение часов браузера и базы) и не раньше 2020 года: заметка о
--      патче шестилетней давности — это опечатка в годе, а не история.
--   6. Версия игры необязательна (до 40 символов): не у всякого объявления
--      есть номер, а требовать его значило бы писать вместо него «n/a».
--   7. Опубликованное видит и невошедший. Архив — только модерация: у
--      устаревшей заметки нет смысла для читателя, но он есть для того, кто
--      отвечает за список.
--   8. Из архива возвращает тоже модерация. Ошибочно убранная заметка иначе
--      пропала бы навсегда: правки-то нет.
--
-- ── ПОЧЕМУ ДВЕРИ — ФУНКЦИИ, А НЕ ПОЛИТИКИ ───────────────────────────────────
--
--   1. Ссылку обязана проверять база. Политика умеет пускать и не пускать
--      строку, но отказ человек увидел бы текстом нарушения ограничения,
--      а здесь нужны слова: «Нужна прямая HTTPS-ссылка на первоисточник».
--      Кроме того, проверка `https://` внутри функции — последний рубеж против
--      `javascript:` в поле href: страница печатает ссылку как есть, и один
--      запрос мимо формы стоил бы исполнения чужого кода в браузере посетителя.
--   2. Дату нельзя проверить политикой: CHECK в Postgres обязан быть
--     _immutable_ и не может смотреть на `now()`. «Не из будущего» — это
--      вычисление в момент записи, то есть функция.
--   3. Право модерации функция спрашивает сама, и различает «не вошёл» и
--      «не модератор» одним словом, как в заявках на гайды.
--   4. Архив и возврат меняют чужую строку — это ровно тот случай, где дверь
--      нужна. Обычный записывающий браузер сюда не ходит, поэтому триггера
--      `forum_set_row_user()` в этой таблице нет: автор подставляется в самой
--      функции из токена.
--
-- ── ЧИСЛА ───────────────────────────────────────────────────────────────────
--
-- Те же значения лежат в CONFIG.forum.limits: updateTitleMin (6),
-- updateTitleMax (120), updateSummaryMin (20), updateSummaryMax (1500),
-- updateSourceNameMin (2), updateSourceNameMax (60), updateUrlMax (500),
-- updateVersionMax (40), updateFutureGraceMinutes (10), updateSourceYearFloor
-- (2020). updateListMax (50) число односторонее: его держит только запрос
-- страницы, базе сравнивать не с чем. Остальное база сторожит сама; в config
-- значения нужны, чтобы черновой режим и форма отказывали ровно тем же словом,
-- что и боевая база. Совпадение чисел и текстов отказа сторожит тест.
--
-- ── ЗАПУСК ──────────────────────────────────────────────────────────────────
--
-- Supabase → SQL Editor → вставить целиком → Run. Скрипт повторный: недостающее
-- создаёт, существующее правит. Ставится после 20260926-starter-checklist.sql
-- и ничего существующего не переопределяет: ни таблицы, ни представления.
--
-- До пуша кода миграция не обязательна: страница обновлений читает список
-- отдельным запросом и по его отказу называет имя этого файла, а не делает вид,
-- что заметок нет. Без миграции остальной форум работает как раньше.

-- ── Шаг 1. Заметки ──────────────────────────────────────────────────────────

create table if not exists public.forum_update_notes (
  id            uuid primary key default gen_random_uuid(),

  /*
    Тип заметки. Три слова и ничего свободного: список, где каждый называет тип
    сам, через месяц читается как свалка синонимов, а фильтровать его невозможно.
  */
  kind          text not null check (kind in ('patch', 'notice', 'issue')),

  /*
    Заголовок: то, что человек читает в списке, не раскрывая заметку. 120
    символов — потому что строка попадает в сетку карточки на телефоне, где
    длиннее уходит в третью строку и ломает выравнивание.
  */
  title         text not null check (char_length(title) between 6 and 120),

  /*
    Само пересказанное изменение. 1500 — потолок: заметка, которая перерастает
   страницу телефона целиком, уже не выжимка, а материал, и месту ему на форуме.
  */
  summary       text not null check (char_length(summary) between 20 and 1500),

  /*
    Как называется источник своими словами («Официальный сайт», «Заметка
    разработчиков в Discord»). Нужен, потому что ссылка без имени — это домен,
    а домен ничего не говорит о том, кто это написал.
  */
  source_name   text not null check (char_length(source_name) between 2 and 60),

  /*
    Прямая ссылка на первоисточник. Проверка регуляркой — второй рубеж после
    функции: в поле href она обязана быть, иначе одно нажатие мимо формы даёт
    чужой код в браузере читателя. Нижняя граница и `https://` на месте и там,
    и здесь, чтобы строка не появилась мимо слов отказа.
  */
  source_url    text not null check (
                  source_url ~ '^https://[^[:space:]]+$'
                  and char_length(source_url) <= 500
                ),

  /*
    Дата публикации у первоисточника, а не дата записи в нашу базу. Разница
    принципиальная: читателя интересует, насколько свежа перемена в игре.
    «Не из будущего» здесь не проверить — CHECK не имеет права смотреть на
    now(), этим говорит функция.
  */
  source_at     timestamptz not null,

  /*
    Номер версии игры — необязательный. Пустая строка, а не null: «не названа»
    и «её нет у первоисточника» для читателя означают одно, и одно поле проще,
    чем поле с двумя видами пустоты.
  */
  game_version  text not null default '' check (char_length(game_version) <= 40),

  /*
    published — в общем списке; archived — убрано из него и видно только
    модерации. Удалять строку нельзя: «мы это публиковали и потом убрали» —
    факт, который должен пережить саму заметку.
  */
  status        text not null default 'published'
                  check (status in ('published', 'archived')),

  author_id     uuid not null references public.forum_users (id) on delete cascade,
  created_at    timestamptz not null default now(),

  /*
    Кто и когда убрал (или вернул) заметку. Держим рядом с собственными полями, а не
    в отдельном журнале: событий два, и журнал ради двух колонок удвоил бы
    количество мест, где нужно искать правду.
  */
  archived_at   timestamptz,
  archived_by   uuid references public.forum_users (id) on delete set null
);

comment on table public.forum_update_notes is
  'Заметки об обновлениях игры, которые публикует модерация: тип, пересказ, ссылка на первоисточник и его дата. Автоматического чтения внешних страниц нет.';

comment on column public.forum_update_notes.source_at is
  'Дата публикации у первоисточника, а не момент добавления в базу: читателя интересует свежесть изменения в игре.';

comment on column public.forum_update_notes.summary is
  'Пересказ изменения своими словами. Обязательная ссылка ниже — замена тому, что текст мог быть переведён или сокращён неверно.';

/* Главный запрос страницы: свежие заметки сверху. */
create index if not exists forum_update_notes_list_idx
  on public.forum_update_notes (status, source_at desc, created_at desc);

alter table public.forum_update_notes enable row level security;

/*
  Опубликованное видит всякий, кто открыл страницу, включая невошедшего:
  ответ на вопрос «что изменилось» не должен требовать учётной записи.
  Архив — только модерации. Не от стыда: устаревшая заметка для читателя —
  ложь, а для того, кто ведёт список, — история и оправдание решения.
*/
drop policy if exists forum_update_notes_read on public.forum_update_notes;
create policy forum_update_notes_read on public.forum_update_notes
  for select using (status = 'published' or public.forum_is_staff());

/*
  Политик записи нет вовсе: браузер сюда не пишет. И публикация, и архив идут
  через функции ниже, где у каждого отказа есть слово.
*/
grant select on public.forum_update_notes to anon, authenticated;

-- ── Шаг 2. Дверь публикации ────────────────────────────────────────────────

/*
  Одна функция на семь полей, и порядок проверок в ней — тот же, что в
  черновом адаптере: право → тип → заголовок → содержание → источник → дата →
  версия. Если их переставить, человек в черновом режиме получит один отказ, а
  в бою другой, и проверки страницы перестанут что-либо значить.

  Возвращает id новой строки, поэтому дочитывать заметку клиент будет отдельным
  запросом к представлению — ник автора знает база, а не этот вызов.
*/
create or replace function public.forum_publish_update_note(
  p_kind         text,
  p_title        text,
  p_summary      text,
  p_source_name  text,
  p_source_url   text,
  p_source_at    timestamptz,
  p_game_version text default ''
)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v_id      uuid;
  v_title   text;
  v_text    text;
  v_name    text;
  v_url     text;
  v_version text;
begin
  /*
    Гость и игрок слышат одно слово: проверка одна — forum_is_staff(), и она не
    различает «не вошёл» и «вошёл без прав». Тот же порядок, что у заявок.
  */
  if not public.forum_is_staff() then
    raise exception 'Заметку об обновлении публикует модерация';
  end if;

  if coalesce(p_kind, '') not in ('patch', 'notice', 'issue') then
    raise exception 'Неизвестный тип заметки: %', p_kind;
  end if;

  v_title := btrim(coalesce(p_title, ''));

  if char_length(v_title) < 6 then
    raise exception 'Заголовок короче 6 символов: по двум словам не понять, о чём заметка';
  end if;

  if char_length(v_title) > 120 then
    raise exception 'Заголовок длиннее 120 символов: на телефоне он уйдёт в три строки';
  end if;

  v_text := btrim(coalesce(p_summary, ''));

  if char_length(v_text) < 20 then
    raise exception 'Содержание короче 20 символов: «обновили игру» — это заголовок, а не заметка';
  end if;

  if char_length(v_text) > 1500 then
    raise exception 'Содержание длиннее 1500 символов: материал о патче пишется на форуме темой';
  end if;

  v_name := btrim(coalesce(p_source_name, ''));

  if char_length(v_name) < 2 then
    raise exception 'Нужно название первоисточника: ссылка без имени — это просто домен';
  end if;

  if char_length(v_name) > 60 then
    raise exception 'Название первоисточника длиннее 60 символов: достаточно короткого «Официальный сайт»';
  end if;

  /*
    Ссылка приводится к нижнему регистру по схеме и проверяется целиком. Здесь
    нет «разрешим http:// и подставим https» — такой редирект ломает ссылку на
    конкретную заметку, а молча пустить http значило бы отдавать адрес открытым
    текстом.
  */
  v_url := btrim(coalesce(p_source_url, ''));

  if v_url !~* '^https://' then
    raise exception 'Нужна прямая HTTPS-ссылка на первоисточник';
  end if;

  /*
    Схему приводим к нижнему регистру: проверка выше терпит «HTTPS://», а CHECK
    таблицы смотрит на `https://` строго. Без этой строки человек, напечатавший
    прописными, получил бы отказ текстом нарушения ограничения.
  */
  v_url := 'https://' || substring(v_url from 9);

  if v_url ~ '\s' then
    raise exception 'Ссылка не может содержать пробелы: похоже, к ней прилипло что-то ещё';
  end if;

  if char_length(v_url) > 500 then
    raise exception 'Ссылка длиннее 500 символов: в карточке она не читается';
  end if;

  if p_source_at is null then
    raise exception 'Нужна дата публикации у первоисточника';
  end if;

  /*
    Десять минут запаса — не педантизм, а разные часы: браузер человека,
    который вводит дату, и сервер базы. Без запаса заметно свежая заметка
    отказывала бы человеку, который ничего не нарушил.
  */
  if p_source_at > now() + interval '10 minutes' then
    raise exception 'Дата первоисточника не может быть из будущего';
  end if;

  if p_source_at < timestamp with time zone '2020-01-01 00:00:00+00' then
    raise exception 'Дата первоисточника раньше 2020 года: похоже, ошиблись годом';
  end if;

  v_version := btrim(coalesce(p_game_version, ''));

  if char_length(v_version) > 40 then
    raise exception 'Номер версии длиннее 40 символов: его не называют так длинно';
  end if;

  insert into public.forum_update_notes
    (kind, title, summary, source_name, source_url, source_at, game_version, author_id)
  values
    (p_kind, left(v_title, 120), left(v_text, 1500), left(v_name, 60),
     left(v_url, 500), p_source_at, left(v_version, 40), auth.uid())
  returning id into v_id;

  return v_id;
end;
$$;

revoke all on function public.forum_publish_update_note(
  text, text, text, text, text, timestamptz, text
) from public, anon;

grant execute on function public.forum_publish_update_note(
  text, text, text, text, text, timestamptz, text
) to authenticated;

comment on function public.forum_publish_update_note(
  text, text, text, text, text, timestamptz, text
) is
  'Публикует заметку об обновлении: держит право модерации, домен типа, длины, обязательную HTTPS-ссылку и дату первоисточника не из будущего.';

-- ── Шаг 3. Дверь архива и возврата ──────────────────────────────────────────

/*
  Одна функция на два противоположных движения. Разделять их на «архив» и «вернуть» —
  значит заводить два отказа на одно и то же состояние; здесь отказ ровно один
  и он называет, в чём заметка уже лежит.

  Условия status внутри UPDATE — та же защита от гонки, что у заявок и
  апелляций: пока модератор смотрел список, второй модератор мог убрать
  заметку, и «архивировать» не должен был бы писать дату повторно.
*/
create or replace function public.forum_set_update_note_archive(
  p_target   uuid,
  p_archived boolean
)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v public.forum_update_notes%rowtype;
begin
  if not public.forum_is_staff() then
    raise exception 'Заметку об обновлении убирает и возвращает модерация';
  end if;

  select * into v from public.forum_update_notes where id = p_target;
  if not found then
    raise exception 'Заметка не найдена';
  end if;

  if p_archived and v.status = 'archived' then
    raise exception 'Эта заметка уже в архиве';
  end if;

  if not p_archived and v.status = 'published' then
    raise exception 'Эта заметка и так опубликована';
  end if;

  update public.forum_update_notes
     set status = case when p_archived then 'archived' else 'published' end,
         archived_at = case when p_archived then now() else null end,
         archived_by = case when p_archived then auth.uid() else null end
   where id = p_target
     and status = case when p_archived then 'published' else 'archived' end;

  if not found then
    raise exception 'Заметка уже изменена: обновите список';
  end if;
end;
$$;

revoke all on function public.forum_set_update_note_archive(uuid, boolean)
  from public, anon;

grant execute on function public.forum_set_update_note_archive(uuid, boolean)
  to authenticated;

comment on function public.forum_set_update_note_archive(uuid, boolean) is
  'Убирает заметку в архив и возвращает из него; строка не удаляется никогда, чтобы решение можно было пересмотреть.';

-- ── Шаг 4. Список с никами ───────────────────────────────────────────────────

/*
  Авторов в таблице две и нигде нет их ников (не дублируем то, что меняется),
  поэтому список выходит представлением — тем же порядком, что
  forum_guide_request_list.

  security_invoker = on обязательно: иначе правило «архив видит только
  модерация» выполнялось бы от имени владельца таблицы, и невошедший получил бы
  чужой архив одним запросом к представлению.

  Никакого присоединения к темам и гайдам здесь нет сознательно: заметка ни к чему
  не пристёгнута, она свидетельствует о внешнем мире, а не о внутреннем.
*/
create or replace view public.forum_update_note_list
with (security_invoker = on) as
select
  n.id,
  n.kind,
  n.title,
  n.summary,
  n.source_name,
  n.source_url,
  n.source_at,
  n.game_version,
  n.status,
  n.author_id,
  a.nick       as author_nick,
  n.created_at,
  n.archived_at,
  b.nick       as archived_by_nick
from public.forum_update_notes n
join public.forum_profiles a on a.id = n.author_id
left join public.forum_profiles b on b.id = n.archived_by;

grant select on public.forum_update_note_list to anon, authenticated;

comment on view public.forum_update_note_list is
  'Заметки об обновлениях с никами автора и того, кто убрал в архив. Право чтения держит политика forum_update_notes: архив виден только модерации.';

-- ОТМЕТКУ ФИДА МОЖНО СНЯТЬ: ДВЕРЬ, КОТОРОЙ НЕ БЫЛО
-- ─────────────────────────────────────────────────────────────────────────────
--
-- ЗАЧЕМ. 15.10.2026 автомат принёс из официальной группы заметку, текстом
-- которой стала шапка чужой страницы-читалки: «Title: Z-Route: Redemption:
-- Posts» вместо «Обновление версии - 14 октября». Причина разобрана и
-- починена 20.10 (вторая форма ответа читалки, без строки автора), но сама
-- мусорная карточка осталась висеть в списке первой, а вместе с ней — отметка
-- `vk:-236547214_45114`.
--
-- СНЯТИЕ — ДВА ШАГА, И ОДИН ИЗ НИХ БЫЛ НЕВОЗМОЖЕН. Заметку убирает
-- `forum_delete_update_note` из шага `20261005-feed-final-delete.sql`. Этому
-- удалению и мешает отметка: пост на стене никуда не делся, и без отметки
-- следующий обход принёс бы его заново. Значит, чтобы новость 14 октября
-- вернулась в список уже разобранной начисто, ключ надо стереть.
--
-- А стереть его было нечем. Таблица заведена намеренно без единой политики на
-- запись: ни INSERT, ни UPDATE, ни DELETE — строку в неё кладёт только
-- definer-функция публикации, и это единственный способ, каким внешний мир
-- получает отметку. Прямой DELETE модератора означал бы дверь без имени: ни в
-- коде, ни в проверках не осталось бы следа, и через месяц никто бы не
-- объяснил, почему автомат перестал приносить половину стены. Поэтому снятие
-- ключа — тоже функция, а не политика: у него есть имя, отказ по той же
-- причине, что у соседних дверей, и проверка в tests/contract.test.js.
--
-- ЧЕМ ЭТО ОПАСНО. Снятая отметка разрешает автомату принести строку снова. Для
-- заметки, которую модерация убрала по делу (не мусор, а настоящая новость,
-- которую здесь видеть не хотят), это значит повторную публикацию через час.
-- Поэтому дверь называет снятый заголовок вслух — он уходит в журнал
-- планировщика, и решение остаётся читаемым, а не молчаливым.

-- ── Функция ──────────────────────────────────────────────────────────────────

/*
  Возвращает название снятой отметки, а не void: планировщик печатает его в
  журнал, и по одной строке видно, какой карточке автомат разрешил вернуться.
  Пустое название допустимо самой таблицей (событие могло приехать без него),
  поэтому возвращаем ровно то, что лежало, без додумывания.
*/
create or replace function public.forum_forget_feed_mark(p_key text)
returns text
language plpgsql security definer set search_path = public
as $$
declare
  v_title text;
begin
  if not public.forum_is_staff() then
    raise exception 'Отметку фида снимает модерация';
  end if;

  /*
    Пустой ключ — не «ничего не найдено», а ошибка вызова: отметка обязана
    называться, иначе прогон стёр бы не то, что модератор имел в виду.
  */
  if p_key is null or btrim(p_key) = '' then
    raise exception 'Ключ отметки не назван';
  end if;

  delete from public.forum_feed_marks
    where feed_key = p_key
    returning title into v_title;

  if not found then
    raise exception 'Отметка не найдена';
  end if;

  return v_title;
end;
$$;

revoke all on function public.forum_forget_feed_mark(text) from public, anon;
grant execute on function public.forum_forget_feed_mark(text) to authenticated;

comment on function public.forum_forget_feed_mark(text) is
  'Снимает отметку фида: позволяет автомату принести строку внешнего мира заново. Убирает ровно одну строку по ключу и возвращает её название; заметку не трогает.';

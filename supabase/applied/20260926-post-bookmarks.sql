-- 2026-09-26. Закладки тем: «вернуться к этой теме позже».
--
-- Идея пришла из большого форума сообщества (Qvaden/zroute-alliance-hub),
-- перенесена на наш SQL: там это таблица saved_posts, а в интерфейсе —
-- «закладки».
--
-- ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
--
-- Тема живёт в ленте несколько дней, потом уезжает вниз и находится только
-- поиском. «Прочитаю вечером» в таком форуме теряется: человек помнит, что
-- разбор полезный, а через два дня не помнит ни названия, ни автора. Закладка
-- — единственное место, где тема дожидается, пока до неё дойдут руки.
--
-- У нас уже есть два способа вернуться к теме: отметка «я здесь был» (она
-- считает непрочитанные ответы) и подписка (она присылает уведомления). Ни
-- один из них не отвечает на «отложи мне это прочитать»: отметка есть у любой
-- открытой темы, а подписка — про будущее, про новые ответы. Закладка же
-- говорит про прошлое: интересен ТОТ текст, что уже написан.
--
-- ── ПРАВИЛО ─────────────────────────────────────────────────────────────────
--
--   1. Закладывают тему, а не ответ. Ответ живёт внутри темы и открывается
--      вместе с ней; отдельная закладка на ответ означала бы список, в
--      котором половину строк не найти без контекста.
--   2. Список приватен: строку видит только тот, кто её поставил. Это не
--      тайна, а отсутствие смысла: чужие закладки — чужой порядок чтения,
--      и показать их можно только в виде «так читают другие», которого здесь
--      нет.
--   3. Закладка НИЧЕГО не сообщает автору: ни числа, ни уведомления. У
--      благодарности наоборот — автор узнаёт, потому что это слово ему.
--      Закладка — действие читателя для себя, и единственный человек,
--      которому она полезна, это сам читатель.
--   4. Закладка — ссылка, а не копия. Хранить текст «про запас» здесь нарочно
--      нечем: архив чужих постов на нашем форуме был бы вторым хранилищем
--      чужих слов, а не списком чтения. Тема, снятую с публикации, список
--      просто не покажет; если же строку темы стирают совсем (каскад по
--      forum_posts), исчезнет и закладка — вместе с тем, к чему она вела.
--   5. Снимается тем же нажатием. Никакой «отмены закладки» отдельной кнопкой
--      не нужно: это обычный переключатель, как свет.
--   6. Число закладок не ограничено, очков не приносит и в репутацию не
--      входит. Приватное полезное действие не должно становиться ещё одной
--      гонкой: кто нажал сто раз, тот ничего не доказал, а сто строк в
--      награду — это награда за клики.
--
-- ── ГДЕ ДВЕРЬ ───────────────────────────────────────────────────────────────
--
--   Двери нет, и это не забывчивость. Функция в базе нужна там, где действие
--   видит чужие строки или решает что-то кроме «это мой»: благодарность
--   считает чужие темы и пишет уведомление, тишина раздела меняет право
--   писать. Здесь одна своя строка, которую ставят и снимают руками:
--   правила доступа достаточно, и оно ниже. Тот же порядок у подписок на
--   темы.
--
--   Отказ без двери тоже выглядит понятно: чужую строку не прочитать и не
--   снять — об этом молча скажут правила доступа, а темы, которой нет, не
--   бывает в кнопке, которую человек нажал.
--
-- ── ЧИСЛА ───────────────────────────────────────────────────────────────────
--
--   В базе их нет: ни лимита, ни срока, ни окна. Единственное число рядом с
--   самой фичей живёт в запросе ленты (config.js, savedWindow) — это сколько
--   последних закладок фильтр готов разворачивать в список, а не сколько
--   закладок разрешено.
--
-- ── ЗАПУСК ──────────────────────────────────────────────────────────────────
--
-- Supabase → SQL Editor → вставить целиком → Run. Скрипт повторный: недостающее
-- создаёт, существующее правит. Ставится после 20260926-author-thanks.sql
-- (порядок здесь не по смыслу, а по времени написания — независимых
-- зависимостей нет).
--
-- Без этой миграции сайт не падает: лента читается как раньше, колонки
-- «в закладках» в ней нет, и кнопка при нажатии получает отказ базы с именем
-- этого файла.
--
-- ── Шаг 1. Сама связь «человек — тема» ──────────────────────────────────────

/*
  Ровно то, что нужно: две колонки и дата. Ни папок, ни меток, ни заметки к
  закладке — у донора их тоже нет, и это не экономия: папки предполагают,
  что человек готов разбирать свой список до того, как им воспользовался.
  На форуме на 200 тем в год это не так.

  Первичный ключ из двух колонок — это и защита от дубля, и указатель для
  «в закладке ли эта тема». Отдельного id на строке нет: адресовать
  закладку нечем.
*/
create table if not exists public.forum_bookmarks (
  post_id    uuid    not null references public.forum_posts (id) on delete cascade,
  user_id    uuid    not null references public.forum_users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

/*
  Лента закладок смотрит на «мое, сверху — позднее». Первый ключ ищет по
  теме (проверка «сохранена ли эта»), а порядок в списке тем не задаёт,
  поэтому ему нужен отдельный указатель.
*/
create index if not exists forum_bookmarks_user_idx
  on public.forum_bookmarks (user_id, created_at desc);

comment on table public.forum_bookmarks is
  'Приватный список «прочитать позже»: одна строка на пару человек—тема, каскад по обеим сторонам.';

-- ── Шаг 2. Кто что видит ────────────────────────────────────────────────────

alter table public.forum_bookmarks enable row level security;

drop policy if exists forum_bookmarks_read on public.forum_bookmarks;
create policy forum_bookmarks_read on public.forum_bookmarks
  for select using (user_id = auth.uid());

drop policy if exists forum_bookmarks_add on public.forum_bookmarks;
create policy forum_bookmarks_add on public.forum_bookmarks
  for insert with check (user_id = auth.uid());

drop policy if exists forum_bookmarks_drop on public.forum_bookmarks;
create policy forum_bookmarks_drop on public.forum_bookmarks
  for delete using (user_id = auth.uid());

/*
  Обновления нет нарочно: передвигать закладку нечем, а «дата постановки»
  по правилу 5 остаётся честной — пережал сегодня, значит снял и поставил,
  и строка становится новой.
*/
grant select, insert, delete on public.forum_bookmarks to authenticated;

-- ── Шаг 3. Чья строка ───────────────────────────────────────────────────────

/*
  Браузер присылает только post_id. Идентификатор человека берётся из токена,
  а не из тела запроса: прислать свой id руками — значит позволить прислать
  чужой, и единственная защита от этого была бы в проверке, которую всё
  равно обходит тот, кто пришёл мимо сайта.

  Так же устроены реакции (forum_set_reaction_user в schema.sql). Функция
  названа общим именем, потому что ниже вешается на три таблицы, а не на
  одну.
*/
create or replace function public.forum_set_row_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  new.user_id := auth.uid();
  return new;
end;
$$;

comment on function public.forum_set_row_user() is
  'Подставляет вставку автора строки из токена: закладки и обе подписки.';

drop trigger if exists forum_bookmarks_user on public.forum_bookmarks;
create trigger forum_bookmarks_user
  before insert on public.forum_bookmarks
  for each row execute function public.forum_set_row_user();

-- ── Шаг 4. Подписки: то же правило, которого им не хватало ─────────────────

/*
  Попутная починка, и она здесь потому, что закладки строились по образцу
  подписок.

  forum_topic_subscriptions (topic-subscriptions.sql) и
  forum_alliance_subscriptions (20260916-forum-community.sql) созданы с тем
  же смыслом — «своя строка», — но правило «id берётся из токена» в них
  записано только в политике доступа, а вставлять его нечем: клиент присылает
  post_id или alliance_id, колонка user_id остаётся пустой, и база отказывает
  не «нет прав», а «не может быть null». То есть кнопка «Подписаться» не
  работала ни у кого, а проверить это можно было только войдя в бой.

  Триггер выше закрывает обе таблицы тем же телом. Повторный пуск безвреден,
  а если на живой базе триггер уже стоит руками — он просто перезапишется
  этим же правилом.
*/
drop trigger if exists forum_topic_subscriptions_user on public.forum_topic_subscriptions;
create trigger forum_topic_subscriptions_user
  before insert on public.forum_topic_subscriptions
  for each row execute function public.forum_set_row_user();

drop trigger if exists forum_alliance_subscriptions_user on public.forum_alliance_subscriptions;
create trigger forum_alliance_subscriptions_user
  before insert on public.forum_alliance_subscriptions
  for each row execute function public.forum_set_row_user();

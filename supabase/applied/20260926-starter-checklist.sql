-- 2026-09-26. Чек-лист новичка: пять первых шагов, которые база видит сама.
--
-- Пункт очереди, перенесённый с форума сообщества (Qvaden/zroute-alliance-hub),
-- где он называется «Первые шаги» и живёт в диалоге на главной плюс страница
-- `/start`.
--
-- ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
--
-- Форум умеет больше, чем человек успевает заметить за первый вечер. Есть
-- закладка, чтобы вернуться к длинному разбору, благодарность, которой говорят
-- спасибо конкретному автору, подписка на альянс, от которой приходят перемены
-- в таблице сил, и строка «о себе», по которой с тобой понимают, кто говорит.
-- Всё это лежит под рукой и при этом не находится: новичок пишет тему и на этом
-- останавливается, потому что не знает, что дальше бывает.
--
-- Достаточность тут не в награде, а в указателе. Поэтому список показывает
-- пять действий короткой строкой и объясняет, зачем каждое, — и исчезает,
-- когда человек их сделал или когда стал не новичком.
--
-- ── ПОЧЕМУ НЕ ДОНОРСКИЙ СПИСОК ──────────────────────────────────────────────
--
-- У донора три шага: выбрать игровой сервер, закрепить псевдоним, принять
-- правила. Ни один из них у нас не переносится как есть.
--
--   Сервера. Мы обслуживаем один сервер, 33, и выбирать не из чего. Шаг был бы
--   всегда выполнен или всегда недоступен — в обоих случаях это ложь в списке.
--
--   Псевдоним. Ник у нас дают при регистрации: без него аккаунт не создаётся, и
--   отдельного «закрепи имя» не существует.
--
--   Правила. Донор держит колонку `rulesAcceptedAt` и на ней держит право
--   писать. У нас правила висят в правой колонке форума постоянно, а согласия
--   никто не собирает. Заводить ради галочки колонку, которую никто не снимает,
--   значит заводить то, что потом придётся чистить руками, — и получать вопрос
--   «почему мне не даёт писать галочка».
--
-- Зато у донора есть то, что мы переносим целиком и без изменений: шаги
-- нигде не отмечаются. Их вычисляют по тем же строкам, что и остальной форум.
-- Так список не может соврать.
--
-- ── ПРАВИЛО ─────────────────────────────────────────────────────────────────
--
--   1. Шагов пять, и они фиксированы: заполнить профиль, ответить в чужой теме,
--      поблагодарить автора, сохранить тему в закладки, подписаться на альянс.
--      Каждый — про то, чего человек не знает, а не про объём написанного.
--   2. Ни один шаг не отмечается нажатием. Галочка, которую ставит сам
--      человек, через неделю враньё: снял закладку — шаг всё ещё «сделан».
--      Здесь шаг закрыт ровно тогда, когда в таблице стоит строка.
--   3. Ничего не хранится. Нет таблицы шагов, нет таблицы отметок, нет колонок.
--      Функция пересобирает ответ на каждый запрос из того, что уже есть.
--   4. Профиль засчитывается любым из трёх: аватар, «о себе», тег альянса.
--      Требовать все три — значит требовать, чтобы новичок писал биографию
--      прежде, чем ему дадут говорить.
--   5. Список видит только сам человек. Модерации не нужно знать, кто не
--      оформил профиль: это не нарушение, а дело вкуса.
--   6. Список живёт ровно `14 дней` с регистрации и потом исчезает, даже если
--      шагов сделано ноль. Дальше это взрослый участник, и напоминать ему про
--      закладки — шуметь. У донора вместо срока была кнопка «продолжить
--      позже», то есть отдельное состояние, которое надо хранить и чистить;
--      срок хранит себя сам и ничего не просит на будущее.
--   7. Выполненных шагов не показывают: когда все пять закрыты, список пуст, а
--      не «5 из 5». Праздник у нас делает страница профиля, где из этих же
--      строк растут значки и уровень.
--
-- ── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ────────────────────────────────────────────────
--
--   Награды за выполнение. Донор тоже не даёт очков: его награда — право
--   пользоваться форумом, а оно у нас не заблокировано ни одним шагом. Выдать
--   баллы за то, что человек воспользовался кнопкой, значит обесценить
--   репутацию, которая растёт из написанного.
--
--   Шага «напиши первую тему». Он есть в значках на странице профиля
--   (`first_post`) и в пустой ленте, которая сама предлагает начать. Дублировать
--   это в списке новичка — плодить два объяснения одного поступка.
--
--   Истории и счётчика «сколько новичков дошли до третьего шага». Раз ничего не
--   хранится, копить нечего; а сводка по шагам — это уже аналитика, ей в
--   панели не место.
--
--   Панельных экранов. Прогресс приватен (правило 5), поэтому у модерации
--   этого списка нет ни в одной вкладке.
--
-- ── ПОЧЕМУ ФУНКЦИЯ, ЕСЛИ ПОЛИТИКИ И ТАК ПУСКАЮТ ─────────────────────────────
--
--   Права на чтение здесь не нужны: каждая строка принадлежит самому
--   вызывающему, и его же политиками она и пущена. Поэтому функция идёт как
--   `security invoker` и ни во что не превращается — единственный способ
--   увидеть чужой список шагов в ней отсутствует по устройству, а не по
--   проверке.
--
--   Функция нужна по другой причине: пять шагов лежат в пяти таблицах. Без неё
--   страница форума делала бы пять отдельных запросов при каждой загрузке, а
--   вместе с ней — один.
--
-- ── ЧИСЛА ───────────────────────────────────────────────────────────────────
--
--   Срок новичка (14 дней) лежит здесь и в `config.js`
--   (`forum.limits.starterWindowDays`); совпадение сторожит тест. Больше этого
--   числа в функции нет ни одного: пределы выдержки, частоту благодарностей и
--   размер окна закладок она не трогает и не должна — шаг «поблагодарить»
--   считается по строке, а не по тому, сколько раз это разрешено.
--
--   Пять ключей шагов (`profile`, `reply`, `thanks`, `save`, `ally`) — общее
--   слово базы и страницы. Русские названия и объяснения живут в коде
--   (`src/forum/rules.js`), как и остальные тексты форума: база отдаёт факт,
--   страница подбирает слова. Порядок строк в ответе не обещан, поэтому страница
--   ищет шаг по ключу, а не по позиции.
--
-- ── ЗАПУСК ──────────────────────────────────────────────────────────────────
--
-- Supabase → SQL Editor → вставить целиком → Run. Скрипт повторный: недостающее
-- создаёт, существующее правит. Порядок установки произвольный: функция ничего
-- не пишет, таблиц не создаёт и чужие представления не пересобирает. Ей нужны
-- только таблицы форума: `forum_users`, `forum_comments`, `forum_thanks`
-- (20260926-author-thanks), `forum_bookmarks` (20260926-post-bookmarks) и
-- `forum_alliance_subscriptions` (20260916-forum-community).
--
-- До пуша кода миграция не обязательна: блок новичка — подсказка, а не дверь.
-- Без функции запрос падает, страница форума это глотает и просто не рисует
-- блок; лента, темы и все кнопки работают как раньше.

-- ── Функция: список первых шагов ─────────────────────────────────────────────

create or replace function public.forum_starter_checklist()
returns table (
  -- Ключ шага: общее слово базы и страницы. Русские слова к нему подбирает
  -- src/forum/rules.js, поэтому переименование ключа здесь — правка в двух
  -- файлах и в тесте, а не только в базе.
  step_key text,
  -- Сделан ли шаг. Считается по строкам других таблиц, здесь не хранится.
  done boolean
)
language sql
stable
-- Не definer: видимы только свои строки, и политики их пускают. Функция ничего
-- не открывает сверх того, что человек и так читает о себе.
security invoker
set search_path = public
as $$
  select u.key, u.done
    from public.forum_users f
    /*
      Пять шагов собраны списком значений: каждый — одно условие над таблицами,
      которые и так растут от обычных действий. Порядок здесь косметический:
      страница смотрит на ключ, а не на номер строки.
    */
   cross join lateral (
     values
       /*
         Профиль засчитывается любым из трёх (правило 4): аватар, «о себе» или
         тег альянса. Пустой профиль — это человек, с которым не с чем
         обращаться по имени альянса, а не нарушитель.
       */
       ('profile', trim(coalesce(f.about, '')) <> ''
                   or trim(coalesce(f.alliance_tag, '')) <> ''
                   or coalesce(f.avatar_url, '') <> ''),
       /*
         Ответ в чужой теме. Удалённый не считается: его сняли за нарушение, и
         радовать себя галочкой за него не за что.
       */
       ('reply',   exists (
         select 1 from public.forum_comments c
          where c.author_id = f.id and c.deleted = false
       )),
       /*
         Благодарность автору — не та, что тебе поставили, а та, что ты сказал.
         Именно она и есть шаг: научиться замечать чужой разбор.
       */
       ('thanks',  exists (
         select 1 from public.forum_thanks t where t.giver_id = f.id
       )),
       /*
         Закладка. Одна сохранённая тема означает, что человек нашёл кнопку
         «прочитать позже» и понял, зачем она.
       */
       ('save',    exists (
         select 1 from public.forum_bookmarks b where b.user_id = f.id
       )),
       /*
         Подписка на альянс — вход в то, что происходит на сервере, а не только
         в чужие посты.
       */
       ('ally',    exists (
         select 1 from public.forum_alliance_subscriptions a
          where a.user_id = f.id
       ))
   ) as u(key, done)
   /*
     Только свой список: идентификатор берётся из токена, а не из тела запроса,
     и попросить чужие шаги нельзя ни напрямую, ни подставив чужой id.
   */
   where f.id = auth.uid()
     /*
       Новичок — две недели (правило 6). Дальше блок исчезает при любом числе
       сделанных шагов, и исчезает навсегда: отдельной отметки «не показывать»
       для этого нет.
     */
     and f.created_at > now() - interval '14 days';
$$;

comment on function public.forum_starter_checklist() is
  'Приватный список «первые шаги» одного человека: пять фактов о том, что он уже воспользовался форумом. Ничего не хранит, считается на каждый запрос, исчезает через 14 дней с регистрации.';

-- Список приватен по правилу 5, поэтому гостю его брать нечем: у него нет ни
-- аккаунта, ни строк. Пустой вызов от anon — не тайна, а бессмыслица, и пусть
-- лучше откажет.
revoke all on function public.forum_starter_checklist() from public, anon;
grant execute on function public.forum_starter_checklist() to authenticated;

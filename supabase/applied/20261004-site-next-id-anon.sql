-- 20261004-site-next-id-anon.sql
-- Снять доступ гостя к свободному номеру альянса.
--
-- ── Зачем отдельный файл ────────────────────────────────────────────────────
--
-- `20261004-site-server-scope.sql` прогнан, и живая проверка после прогона
-- дала unexpected 200: гостный ключ вызвал `site_next_alliance_id()` и получил
-- число. Функция заведена для панели, и реестр обещает, что гостю она не
-- открыта. Файл шага уже выполнен на боевой базе, а прогнанные миграции здесь
-- не переписываются (см. supabase/README.md): исправление — отдельный короткий
-- шаг, который можно прогнать не читая предыдущий.
--
-- ── Почему прежняя строка не сработала ──────────────────────────────────────
--
-- Postgres при `create function` выдаёт право EXECUTE роли PUBLIC — это
-- значение по умолчанию, а не наш выбор. `revoke execute ... from anon` снимает
-- право у самого `anon`, но `anon` входит в `PUBLIC`, и унаследованное право
-- остаётся: отказ для гостя не появляется. Форма, которой проект пользуется во
-- всех прежних миграциях, — `revoke all on function public.<имя>(<аргументы>)
-- from public, anon;` (см. applied/20260926-spam-signals.sql и десятки
-- соседних строк): вместе с PUBLIC снимается и наследие у anon, а
-- authenticated возвращается следующей строкой.
--
-- Порядок строк важен: сначала снятие с PUBLIC, потом явный grant для
-- `authenticated`. Наоборот тоже работает, но читается как «сначала дали,
-- потом отобрали назад», и при правке порядок легко переставить с потерей
-- права у панели.
--
-- ── Проверка после прогона ──────────────────────────────────────────────────
--
-- Гость (публичный ключ сайта, без входа): вызов `rpc/site_next_alliance_id`
-- обязан ответить 401 с текстом «permission denied for function
-- site_next_alliance_id» — тем же кодом 42501, которым база отвечает и на
-- `forum_spam_signals`. Панель под входом отвечает числом: экран «Альянсы»
-- создаёт новую строку как раньше.
--
-- `notify pgrst, 'reload schema'` здесь не нужен: кэш схемы API хранит
-- составы аргументов и возвращаемые колонки, а права база сверяет в момент
-- вызова. Состав аргументов этой функции не менялся.

revoke all on function public.site_next_alliance_id() from public, anon;
grant execute on function public.site_next_alliance_id() to authenticated;

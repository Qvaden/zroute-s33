/*
  Состояние обхода помнит заметку, которой в базе нет.

  1 октября разовая чистка дублей убрала лишние заметки о версии, и вместе с
  ними ушла та, на которую ссылка `last_note_id` указывает сейчас. Отметок фида
  (`forum_feed_marks`) тогда ещё не было — их завёл шаг
  `20261005-feed-final-delete.sql`, — поэтому ключ удалённой заметки никуда не
  лёг и опознать «это убирали насовсем» больше нечем.

  Что из этого следует видит каждый посетитель вкладки «Обновления игры»:
  состояние говорит «опубликовано 1.37.06», обе площадки стоят на 1.37.06, и
  планировщик честно молчит — а в списке последней числится заметка 1.37.01.
  Автомат не сломался: он не переизлагает то, что, по его записи, уже изложил.

  Правка возвращает состояние к тому, что реально лежит в списке: номера версий
  и номер последней заметки берутся из самой новой заметки магазинов. Дверь
  публикации на следующий же обход соберёт заметку о 1.37.06 и положит её
  в список — это не задвоение, а ровно то, что игрок должен увидеть.

  Файл точечный и потому условный: трогается только строка состояния, чья
  заметка не найдена. База с целой ссылкой проходит мимо него молча, поэтому
  повторный запуск и запуск на новой базе (где состояние пустое и заметок нет
  вовсе) безвредны.
*/

with newest as (
  /*
    Берём последнюю заметку именно магазинов: заметки из группы ВК и слова
    модерации от руки номера версии не несут, и по ним сверять состояние
    нельзя.
  */
  select n.id,
         (regexp_match(n.game_version, 'Android ([0-9.]+)'))[1] as android,
         (regexp_match(n.game_version, 'iOS ([0-9.]+)'))[1] as ios
    from public.forum_update_notes n
   where n.source_name = 'Google Play и App Store'
   order by n.source_at desc, n.created_at desc
   limit 1
),
stale as (
  select s.id
    from public.forum_store_state s
    left join public.forum_update_notes n on n.id = s.last_note_id
   where s.last_note_id is not null
     and n.id is null
)
update public.forum_store_state s
   set android_version = coalesce(newest.android, ''),
       ios_version     = coalesce(newest.ios, ''),
       last_note_id    = newest.id,
       last_run_text   = 'Состояние сверено со списком: заметки, которую оно помнило, в базе нет.'
  from stale
  left join newest on true
 where s.id = stale.id;

/*
  Отчёт последнего обхода при этом не тронут временем (`last_run_at`): он и
  правда был, и снять его значило бы соврать, что автомат не запускался.
*/

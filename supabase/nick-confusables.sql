-- ── Расширенная защита от confusable-ников ─────────────────────────────────
--
-- Обновляет forum_nick_key (NFKC + расширенная карта двойников) и пересоздаёт
-- уникальный индекс, чтобы существующие строки были пересчитаны по новому ключу.
--
-- Если при пересоздании индекс упадёт на конфликте — значит, в базе уже есть
-- похожие ники (друг использовал диакритику или цифры вместо букв). Их нужно
-- переименовать через forum_rename_nick_as с причиной «confusable» и повторить
-- миграцию.
--
-- Требуется PostgreSQL 13+ (normalize). Повторный запуск безопасен.

-- ── Функция ключа (обновлена) ──────────────────────────────────────────────
--
-- NFKC нормализует full-width буквы (ｋ→k), лигатуры и комбинированные символы
-- (é = e + accent), затем translate подменяет «двойники»:
--   • кириллические «латинские» буквы (Крeмль == Кремль);
--   • украинские і/ї (== i), є (== e);
--   • греческие ο/ι/ε/ρ/τ/χ/κ/ν (== o/i/e/p/t/x/k/v);
--   • латинские с диакритикой (é/à/ä/ø/ł/etc → e/a/a/o/i);
--   • цифры и похожие буквы: 0 == o, 1 == l == i.
-- Разделители (пробел, _, -) не трогаем: «Ковыль» и «Ковыль-33» —
-- разные люди, их нельзя склеивать.

create or replace function public.forum_nick_key(nick text)
returns text
language sql immutable
as $$
  select translate(
    lower(normalize(coalesce(nick, ''), NFKC)),
    'авекмнорстухіїєοικερτχνàáâãäåąèéêëēěęìíîïīıòóôõöøōùúûüūũůñńçćčšśŝžźýÿł01l',
    'abekmhopctuyxiieoieptxkvaaaaaaeeeeeeeiiiiiiooooooouuuuuuunccccssszzzyyiiii'
  );
$$;

-- ── Пересчёт стоп-листа ────────────────────────────────────────────────────
--
-- reserved_nicks хранит КЛЮЧИ, вычисленные по старой функции. Новая функция
-- даёт другие ключи для ников с заглавными буквами и новыми двойниками, —
-- старые записи перестали бы ловиться при проверке. Пере-прогоняем сохранённые
-- ключи через новую функцию: результат совпадает с новой функцией от исходного
-- ника. Если два старых ключа сливаются в один новый — оставляем одну запись.

delete from public.reserved_nicks a
  using public.reserved_nicks b
 where a.ctid < b.ctid
   and public.forum_nick_key(a.nick) = public.forum_nick_key(b.nick);

update public.reserved_nicks
   set nick = public.forum_nick_key(nick);

-- ── Пересоздание уникального индекса ───────────────────────────────────────
--
-- Текущий индекс содержит вычисленные по СТАРОЙ функции ключи существующих
-- строк. Пересоздание заставляет PostgreSQL вычислить ключи заново по новой
-- функции и убедиться в уникальности.

drop index if exists forum_users_nickkey_uniq;
create unique index if not exists forum_users_nickkey_uniq
  on public.forum_users (public.forum_nick_key(nick))
  where btrim(nick) <> '';